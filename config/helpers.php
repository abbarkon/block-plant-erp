             VALUES (?, ?, ?, ?, ?, ?, NOW())
             ON DUPLICATE KEY UPDATE
                reason = VALUES(reason),
                evidence_reference = VALUES(evidence_reference),
                revoked_by = VALUES(revoked_by),
                revoked_at = NOW()"
        );
        $stmt->execute([
            $employeeId,
            $from,
            $to,
            mb_substr($reason, 0, 4000),
            $evidenceReference !== '' ? mb_substr($evidenceReference, 0, 255) : null,
            $userId > 0 ? $userId : null,
        ]);
        $idStmt = $pdo->prepare(
            "SELECT id FROM attendance_warning_revocations
             WHERE employee_id = ? AND period_from = ? AND period_to = ?"
        );
        $idStmt->execute([$employeeId, $from, $to]);
        return (int) $idStmt->fetchColumn();
    } catch (Throwable $e) {
        return 0;
    }
}

/**
 * Remove a revocation and its evidence so the warning becomes active again.
 */
function restore_attendance_warning($employeeId, $from, $to) {
    global $pdo;
    $employeeId = (int) $employeeId;
    [$from, $to] = attendance_report_bounds($from, $to);
    if ($employeeId <= 0) {
        return false;
    }
    ensure_attendance_warning_schema();
    try {
        $idStmt = $pdo->prepare(
            "SELECT id FROM attendance_warning_revocations
             WHERE employee_id = ? AND period_from = ? AND period_to = ?"
        );
        $idStmt->execute([$employeeId, $from, $to]);
