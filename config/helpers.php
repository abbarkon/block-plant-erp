function revoke_attendance_warning($employeeId, $from, $to, $reason, $evidenceReference, $userId) {
    global $pdo;
    $employeeId = (int) $employeeId;
    $userId = (int) $userId;
    [$from, $to] = attendance_report_bounds($from, $to);
    $reason = trim((string) $reason);
    $evidenceReference = trim((string) $evidenceReference);
