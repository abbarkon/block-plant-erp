    } catch (Throwable $e) {
        return false;
    }
}

/**
 * Resolve the user account that belongs to an employee.
 *
 * Employees have no user_id in the base schema, so the link is resolved from an
 * explicit employees.user_id column when an installation has one, then from an
 * exact (case-insensitive) name match, then from a unique email match between
 * employees.email and users.username. Ambiguous matches return 0 so a warning
 * letter is never sent to the wrong person.
 *
 * @param array<string,mixed> $employee
 * @return int users.id, or 0 when the employee has no matching account.
 */
function employee_user_account_id($employee) {
    global $pdo;
    $employeeId = (int) ($employee['id'] ?? 0);
    if ($employeeId <= 0) {
        return 0;
    }
    static $hasUserIdColumn = null;
    try {
        if ($hasUserIdColumn === null) {
            $hasUserIdColumn = (bool) $pdo->query("SHOW COLUMNS FROM employees LIKE 'user_id'")->fetch();
        }
        if ($hasUserIdColumn) {
            $stmt = $pdo->prepare(
                "SELECT u.id
                 FROM employees e
                 JOIN users u ON u.id = e.user_id AND u.status = 1
                 WHERE e.id = ?"
            );
            $stmt->execute([$employeeId]);
            $userId = (int) $stmt->fetchColumn();
            if ($userId > 0) {
                return $userId;
            }
        }

        $name = trim((string) ($employee['name'] ?? ''));
        if ($name !== '') {
            $stmt = $pdo->prepare(
                "SELECT id FROM users
                 WHERE status = 1 AND LOWER(TRIM(name)) = LOWER(?)
                 ORDER BY id LIMIT 2"
            );
            $stmt->execute([$name]);
            $ids = $stmt->fetchAll(PDO::FETCH_COLUMN);
            if (count($ids) === 1) {
                return (int) $ids[0];
            }
        }

        $email = strtolower(trim((string) ($employee['email'] ?? '')));
        if ($email !== '') {
            // Placeholder addresses shared by several employees are not an identity.
            $stmt = $pdo->prepare(
                "SELECT COUNT(*) FROM employees
                 WHERE LOWER(TRIM(COALESCE(email, ''))) = ?"
            );
            $stmt->execute([$email]);
            if ((int) $stmt->fetchColumn() === 1) {
                $stmt = $pdo->prepare(
                    "SELECT id FROM users
                     WHERE status = 1 AND LOWER(TRIM(username)) = ?
                     ORDER BY id LIMIT 2"
                );
                $stmt->execute([$email]);
                $ids = $stmt->fetchAll(PDO::FETCH_COLUMN);
                if (count($ids) === 1) {
                    return (int) $ids[0];
                }
            }
        }
    } catch (Throwable $e) {
        return 0;
    }
    return 0;
}

/**
 * Users who should hear about an issued warning letter: administrators, HR
 * managers and HR users allowed to print or approve warning letters.
 *
 * @return array<int,array{id:int,name:string}>
 */
function attendance_warning_notify_recipients($excludeUserId = null) {
    global $pdo;
    $excludeUserId = (int) $excludeUserId;
    $sql = "SELECT DISTINCT u.id, u.name
            FROM users u
            LEFT JOIN user_permissions up ON up.user_id = u.id AND up.module = 'hr'
            LEFT JOIN hr_permission_grants g ON g.user_id = u.id
            WHERE u.status = 1
              AND (
                  LOWER(u.role) IN ('admin', 'administrator', 'hr')
                  OR (LOWER(COALESCE(u.department, '')) IN ('hr', 'human resources')
                      AND LOWER(COALESCE(u.department_role, '')) = 'manager')
                  OR up.can_edit = 1 OR up.can_approve = 1
                  OR g.can_edit = 1 OR g.can_approve = 1
              )
            ORDER BY u.id";
    try {
        $rows = $pdo->query($sql)->fetchAll();
    } catch (Throwable $e) {
        // Older databases may not have user_permissions or the grant table yet.
        try {
            $rows = $pdo->query(
                "SELECT id, name FROM users
                 WHERE status = 1 AND LOWER(role) IN ('admin', 'administrator', 'hr', 'manager')
                 ORDER BY id"
            )->fetchAll();
        } catch (Throwable $e2) {
            return [];
        }
    }
    $recipients = [];
    foreach ($rows as $row) {
        $id = (int) $row['id'];
        if ($id <= 0 || $id === $excludeUserId) {
            continue;
        }
        $recipients[$id] = ['id' => $id, 'name' => (string) $row['name']];
    }
    return array_values($recipients);
}

/**
 * Record a generated warning letter and notify HR and the employee once.
 *
 * A warning letter is rebuilt from live attendance data on every page load, so
 * the issue is deduplicated by the employee plus the exact set of absence
 * dates. Re-opening or re-printing the same letter therefore never sends a
 * second notification, while a warning that later covers additional absences
 * is treated as a new issue.
 *
 * @param array<string,mixed> $employee
 * @param array<string,mixed> $summary attendance_absence_summary() output
 * @param string              $reference deterministic WRN-... reference
 * @param int                 $issuedBy  users.id of the HR user who opened it
 * @param string              $issuedByName display name of that user
 * @return array{notified:bool,duplicate:bool,recipients:int,error:?string}
 */
function attendance_warning_issue($employee, $from, $to, $summary, $reference, $issuedBy = 0, $issuedByName = '') {
    global $pdo;
    $employeeId = (int) ($employee['id'] ?? 0);
    [$from, $to] = attendance_report_bounds($from, $to);
    $dates = array_values(array_filter(array_map('strval', (array) ($summary['dates'] ?? []))));
    sort($dates);
    $absenceDays = (int) ($summary['total'] ?? count($dates));
    $issuedBy = (int) $issuedBy;
    $reference = trim((string) $reference);
    $result = ['notified' => false, 'duplicate' => false, 'recipients' => 0, 'error' => null];

    if ($employeeId <= 0 || $absenceDays <= 0) {
        $result['error'] = 'invalid';
        return $result;
    }

    $absenceHash = md5(implode(',', $dates));

    try {
        ensure_attendance_warning_schema();
        ensure_notifications_schema();

        $pdo->beginTransaction();
        $insert = $pdo->prepare(
            "INSERT IGNORE INTO attendance_warning_issues
                (employee_id, period_from, period_to, absence_hash, absence_days, reference, issued_by, issued_at)
             VALUES (?, ?, ?, ?, ?, ?, ?, NOW())"
        );
        $insert->execute([
            $employeeId,
            $from,
            $to,
            $absenceHash,
            $absenceDays,
            mb_substr($reference, 0, 80),
            $issuedBy > 0 ? $issuedBy : null,
        ]);
        if ($insert->rowCount() === 0) {
            $pdo->commit();
            $result['duplicate'] = true;
            return $result;
        }
        $issueId = (int) $pdo->lastInsertId();

        $isAmharic = app_lang() === 'am';
        $name = trim((string) ($employee['name'] ?? ''));
        $code = trim((string) ($employee['employee_code'] ?? ''));
        $periodLabel = format_app_date($from) . ' – ' . format_app_date($to);
        $daysLabel = number_format($absenceDays);
        $codeLabel = $code !== '' ? ' (' . $code . ')' : '';
        $referenceLabel = $reference !== '' ? $reference : 'WRN-' . $employeeId;

        if ($isAmharic) {
            $hrMessage = 'የማስጠንቀቂያ ደብዳቤ ' . $referenceLabel . ' ለ' . $name . $codeLabel
                . ' በ' . $daysLabel . ' የሥራ ቀናት መቅረት (' . $periodLabel . ') ተሰጠ።';
            $employeeMessage = 'ለእርስዎ በ' . $daysLabel . ' የሥራ ቀናት መቅረት (' . $periodLabel
                . ') የማስጠንቀቂያ ደብዳቤ ተሰጥቷል። ማጣቀሻ፦ ' . $referenceLabel
                . '። መዝገቡ የተሳሳተ ከሆነ ከሰው ኃይል ጋር ይገናኙ።';
        } else {
            $hrMessage = 'Warning letter ' . $referenceLabel . ' issued to ' . $name . $codeLabel
                . ' for ' . $daysLabel . ' working days of absence (' . $periodLabel . ').';
            $employeeMessage = 'HR issued you a warning letter for ' . $daysLabel
                . ' working days of absence (' . $periodLabel . '). Reference: ' . $referenceLabel
                . '. Contact HR if this record is incorrect.';
        }
        if ($issuedByName !== '') {
            $hrMessage .= $isAmharic ? ' ያዘጋጀው፦ ' . $issuedByName . '።' : ' Issued by ' . $issuedByName . '.';
        }

        $hrLink = '/block_plant/hr/attendance_warning_print.php?' . http_build_query([
            'employee_id' => $employeeId,
            'from' => $from,
            'to' => $to,
        ]);

        $notified = 0;
        $seen = [];
        foreach (attendance_warning_notify_recipients($issuedBy) as $recipient) {
            if (isset($seen[$recipient['id']])) {
                continue;
            }
            $seen[$recipient['id']] = true;
            if (notify_user($recipient['id'], $hrMessage, $hrLink)) {
                $notified++;
            }
        }

        $employeeUserId = employee_user_account_id($employee);
        if ($employeeUserId > 0 && $employeeUserId !== $issuedBy && !isset($seen[$employeeUserId])) {
            if (notify_user($employeeUserId, $employeeMessage, null)) {
                $notified++;
            }
        }

        $update = $pdo->prepare("UPDATE attendance_warning_issues SET notified_count = ? WHERE id = ?");
        $update->execute([$notified, $issueId]);

        $pdo->commit();
        $result['notified'] = $notified > 0;
        $result['recipients'] = $notified;
    } catch (Throwable $e) {
        if ($pdo->inTransaction()) {
            $pdo->rollBack();
        }
        error_log('Attendance warning notification failed: ' . $e->getMessage());
        $result['error'] = $e->getMessage();
    }
    return $result;
}

