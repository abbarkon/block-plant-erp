/**
 * Strict YYYY-MM-DD validation that rejects impossible dates (2026-02-30).
 */
function is_valid_date_string($value) {
    if (!is_string($value) || !preg_match('/^\d{4}-\d{2}-\d{2}$/', $value)) {
        return false;
    }
    $dt = DateTime::createFromFormat('Y-m-d', $value);
    return $dt !== false && $dt->format('Y-m-d') === $value;
}

/**
 * Straight-line depreciation for a fixed asset as of a given date.
 * Uses the asset's useful life when available, otherwise the category rate.
 */
function calculate_asset_depreciation(array $asset, $asOf = null) {
    $asOf = $asOf ?: date('Y-m-d');
    $cost = (float) ($asset['purchase_cost'] ?? 0);
    $salvage = min((float) ($asset['salvage_value'] ?? 0), $cost);
    $base = max(0, $cost - $salvage);
    $life = (int) ($asset['useful_life'] ?? 0);
    $rate = (float) ($asset['depreciation_rate'] ?? 0);

    if ($life > 0) {
        $annual = $base / $life;
        $method = 'Straight-line / useful life';
        $maxAccumulated = $base;
    } elseif ($rate > 0) {
        $annual = $cost * ($rate / 100);
        $method = 'Category rate (' . number_format($rate, 2) . '% p.a.)';
        $maxAccumulated = $base;
    } else {
        $annual = 0.0;
        $method = 'No depreciation policy';
        $maxAccumulated = 0.0;
    }

    $yearsHeld = 0.0;
    $accumulated = 0.0;
    try {
        $purchase = new DateTime($asset['purchase_date']);
        $end = new DateTime($asOf);
        if ($end >= $purchase) {
            $yearsHeld = ((int) $purchase->diff($end)->days) / 365.25;
            $accumulated = min($annual * $yearsHeld, $maxAccumulated);
        }
    } catch (Throwable $e) {
        // Invalid dates yield zero depreciation rather than a fatal error.
    }
    $accumulated = round($accumulated, 2);

    return [
        'cost' => $cost,
        'salvage' => $salvage,
        'base' => $base,
        'annual' => round($annual, 2),
        'years' => $yearsHeld,
        'accumulated' => $accumulated,
        'book' => round($cost - $accumulated, 2),
        'method' => $method,
        'fully_depreciated' => $base > 0 && $accumulated >= $base - 0.005,
    ];
}

