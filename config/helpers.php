/**
 * Delete all evidence files and rows for a revocation.
 */
function delete_attendance_warning_evidence($revocationId) {
    global $pdo;
    $revocationId = (int) $revocationId;
    if ($revocationId <= 0) {
        return false;
    }
    $files = attendance_warning_evidence_files($revocationId);
    $base = warning_evidence_base_dir(false);
    if ($base !== '') {
        foreach ($files as $file) {
            $path = $base . '/' . $revocationId . '/' . basename((string) $file['stored_name']);
            if (is_file($path)) {
                @unlink($path);
            }
        }
    }
    try {
        $pdo->prepare("DELETE FROM attendance_warning_revocation_files WHERE revocation_id = ?")->execute([$revocationId]);
        if ($base !== '') {
            $dir = $base . '/' . $revocationId;
            if (is_dir($dir)) {
                @rmdir($dir);
            }
        }
        return true;
    } catch (Throwable $e) {
        return false;
    }
}

