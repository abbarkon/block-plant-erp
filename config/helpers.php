/**
 * Ensure the attendance_submissions table exists. This is the HR -> Finance
 * hand-off record: HR submits attendance for a month, finance approves it,
 * and only then can payroll be generated for that period.
 * Idempotent; safe to call at the top of any page that touches it.
 */
function ensure_attendance_submission_schema() {
    global $pdo;
    static $checked = false;
    if ($checked) {
        return;
    }
    $pdo->exec("CREATE TABLE IF NOT EXISTS attendance_submissions (
        id INT AUTO_INCREMENT PRIMARY KEY,
        month INT NOT NULL,
        year INT NOT NULL,
        submitted_by INT NOT NULL,
        submitted_at DATETIME NOT NULL,
        status ENUM('pending','approved','rejected') DEFAULT 'pending',
