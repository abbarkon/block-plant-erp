/**
 * Only allow notification links that cannot execute script. Stored notification
 * links are generated by the app, but messages can include user-supplied text
 * in older records, so reject javascript:/data: and protocol-relative URLs.
 */
function safe_notification_link($link) {
    $link = trim((string) $link);
    if ($link === '') {
        return '';
    }
    if (str_starts_with($link, '//')) {
        return '';
    }
    if (str_starts_with($link, '/block_plant/') || (str_starts_with($link, '/') && !str_starts_with($link, '//'))) {
        return $link;
    }
    if (preg_match('#^https?://#i', $link)) {
        return $link;
    }
    return '';
}

