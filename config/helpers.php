        approved_at DATETIME,
        FOREIGN KEY (submitted_by) REFERENCES users(id),
        FOREIGN KEY (approved_by) REFERENCES users(id),
        UNIQUE KEY unique_period (month, year)
    )");
    $checked = true;
}

/**
 * Fetch the attendance submission for a period, or null when HR has not
 * submitted attendance for that month/year yet.
 */
function get_attendance_submission($month, $year) {
