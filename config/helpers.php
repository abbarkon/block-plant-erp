/**
 * Mark every date of an approved leave request as "leave" in the attendance
 * register. Uses the unique (employee_id, attendance_date) key so an existing
 * absent/present row is upgraded to leave instead of duplicated.
 *
 * @return int number of dates written
 */
function sync_leave_to_attendance($employeeId, $fromDate, $toDate, $leaveType, $requestId = 0) {
    global $pdo;
    $employeeId = (int) $employeeId;
    if ($employeeId <= 0 || !is_valid_date_string($fromDate) || !is_valid_date_string($toDate) || $toDate < $fromDate) {
        return 0;
    }

    $note = 'Approved ' . trim((string) $leaveType) . ' leave' . ((int) $requestId > 0 ? ' (request #' . (int) $requestId . ')' : '');
    try {
        $joinStmt = $pdo->prepare("SELECT date_of_joining FROM employees WHERE id = ?");
        $joinStmt->execute([$employeeId]);
        $joiningDate = $joinStmt->fetchColumn();
        if (!empty($joiningDate) && $fromDate < $joiningDate) {
            $fromDate = $joiningDate;
            if ($toDate < $fromDate) {
                return 0;
            }
        }

        $stmt = $pdo->prepare(
            "INSERT INTO attendance (employee_id, attendance_date, working_hours, status, notes)
             VALUES (?, ?, 0, 'leave', ?)
             ON DUPLICATE KEY UPDATE status = 'leave', working_hours = 0,
                 notes = IF(notes IS NULL OR notes = '', VALUES(notes), notes)"
        );
        $saved = 0;
        $cursor = strtotime($fromDate);
        $last = strtotime($toDate);
        while ($cursor !== false && $cursor <= $last) {
            $stmt->execute([$employeeId, date('Y-m-d', $cursor), $note]);
            $saved++;
            $cursor = strtotime('+1 day', $cursor);
        }
        return $saved;
    } catch (Throwable $e) {
        return 0;
    }
}

/**
 * Working-day rule used by attendance reminders. Defaults to Monday-Friday.
 * Define ATTENDANCE_WORKING_DAYS (1=Mon ... 7=Sun) before this helper is loaded
 * to change the working week, for example define('ATTENDANCE_WORKING_DAYS', [1,2,3,4,5,6]);
 * if Saturday is a working day.
 */
function is_working_day($date = null, ?array $workingDays = null) {
    $date = $date ?: date('Y-m-d');
    if (!is_valid_date_string($date)) {
        return false;
    }
    if ($workingDays === null) {
        $workingDays = defined('ATTENDANCE_WORKING_DAYS')
            ? (array) ATTENDANCE_WORKING_DAYS
            : [1, 2, 3, 4, 5];
    }
    $workingDays = array_map('intval', $workingDays);
    return in_array((int) date('N', strtotime($date)), $workingDays, true);
}

/**
 * Active employees with no attendance row for a given date.
 *
 * @return array{date:string,active_count:int,recorded_count:int,missing_count:int,is_complete:bool,missing:array<int,array>}
 */
function attendance_missing_for_date($date) {
    global $pdo;

    $result = [
        'date' => (string) $date,
        'active_count' => 0,
        'recorded_count' => 0,
        'missing_count' => 0,
        'is_complete' => true,
        'missing' => [],
    ];
    if (!is_valid_date_string($date)) {
        return $result;
    }

    try {
        $countStmt = $pdo->prepare("SELECT COUNT(*) FROM employees WHERE status = 1 AND (date_of_joining IS NULL OR date_of_joining <= ?)");
        $countStmt->execute([$date]);
        $activeCount = (int) $countStmt->fetchColumn();
        $stmt = $pdo->prepare(
            "SELECT e.id, e.name, e.employee_code, e.department
             FROM employees e
             LEFT JOIN attendance a ON a.employee_id = e.id AND a.attendance_date = ?
             WHERE e.status = 1
               AND (e.date_of_joining IS NULL OR e.date_of_joining <= ?)
               AND a.id IS NULL
             ORDER BY e.name"
        );
        $stmt->execute([$date, $date]);
        $missing = $stmt->fetchAll();

        $missingCount = count($missing);
        $result['active_count'] = $activeCount;
        $result['missing_count'] = $missingCount;
        $result['recorded_count'] = max(0, $activeCount - $missingCount);
        $result['is_complete'] = $activeCount === 0 || $missingCount === 0;
        $result['missing'] = $missing;
    } catch (Throwable $e) {
        // If the tables are unavailable, do not raise a false reminder.
    }

    return $result;
}

/**
 * Attendance and leave figures that reduce pay for one employee in a period.
 *
 * Deductible days = recorded absences + half of each half-day + approved
 * "Unpaid Leave" dates that are not already recorded as absent/half-day.
 * Paid leave types (sick/casual/annual/emergency) do not reduce pay.
 *
 * A 30-day month is used, matching the overtime basis (basic / 240 hours).
 *
 * @return array{absent_days:float,half_days:int,unpaid_leave_days:int,unpaid_days:float,daily_rate:float,deduction:float,details:string}
 */
function payroll_attendance_summary($employeeId, $month, $year, $basicSalary) {
    global $pdo;
    $employeeId = (int) $employeeId;
    $month = (int) $month;
    $year = (int) $year;

    $summary = [
        'absent_days' => 0.0,
        'half_days' => 0,
        'unpaid_leave_days' => 0,
        'unpaid_days' => 0.0,
        'daily_rate' => 0.0,
        'deduction' => 0.0,
        'details' => '',
    ];
    if ($employeeId <= 0 || $month < 1 || $month > 12 || $year < 1900) {
        return $summary;
    }

    $start = sprintf('%04d-%02d-01', $year, $month);
    $end = date('Y-m-t', strtotime($start));

    try {
        $stmt = $pdo->prepare(
            "SELECT COALESCE(SUM(CASE WHEN a.status = 'absent' THEN 1 ELSE 0 END), 0) AS absent_days,
                    COALESCE(SUM(CASE WHEN a.status = 'half-day' THEN 1 ELSE 0 END), 0) AS half_days
             FROM attendance a
             JOIN employees e ON e.id = a.employee_id
             WHERE a.employee_id = ? AND a.attendance_date BETWEEN ? AND ?
               AND (e.date_of_joining IS NULL OR a.attendance_date >= e.date_of_joining)"
        );
        $stmt->execute([$employeeId, $start, $end]);
        $row = $stmt->fetch() ?: [];
        $absentDays = (float) ($row['absent_days'] ?? 0);
        $halfDays = (int) ($row['half_days'] ?? 0);
    } catch (Throwable $e) {
        $absentDays = 0.0;
        $halfDays = 0;
    }

    // Approved unpaid leave dates that fall inside this payroll period.
    $unpaidDates = [];
    try {
        $stmt = $pdo->prepare(
            "SELECT from_date, to_date FROM leave_requests
             WHERE employee_id = ? AND status = 'approved'
               AND LOWER(leave_type) LIKE '%unpaid%'
               AND from_date <= ? AND to_date >= ?"
        );
        $stmt->execute([$employeeId, $end, $start]);
        foreach ($stmt->fetchAll() as $leave) {
            $cursor = max(strtotime($leave['from_date']), strtotime($start));
            $last = min(strtotime($leave['to_date']), strtotime($end));
            while ($cursor !== false && $cursor <= $last) {
                $unpaidDates[date('Y-m-d', $cursor)] = true;
                $cursor = strtotime('+1 day', $cursor);
            }
        }
    } catch (Throwable $e) {
        $unpaidDates = [];
    }

    // Never count the same day twice: skip unpaid-leave dates already flagged
    // as absent or half-day in the attendance register.
    if ($unpaidDates) {
        try {
            $dates = array_keys($unpaidDates);
            $placeholders = implode(',', array_fill(0, count($dates), '?'));
            $stmt = $pdo->prepare(
                "SELECT a.attendance_date FROM attendance a
                 JOIN employees e ON e.id = a.employee_id
                 WHERE a.employee_id = ? AND a.status IN ('absent', 'half-day')
                   AND a.attendance_date IN ($placeholders)
                   AND (e.date_of_joining IS NULL OR a.attendance_date >= e.date_of_joining)"
            );
            $stmt->execute(array_merge([$employeeId], $dates));
            foreach ($stmt->fetchAll(PDO::FETCH_COLUMN) as $covered) {
                unset($unpaidDates[$covered]);
            }
        } catch (Throwable $e) {
            // Keep the leave dates if the overlap check fails.
        }
    }

    $unpaidLeaveDays = count($unpaidDates);
    $unpaidDays = $absentDays + ($halfDays * 0.5) + $unpaidLeaveDays;
    $dailyRate = ((float) $basicSalary) / 30;
    $deduction = round($unpaidDays * $dailyRate, 2);

    $parts = [];
    if ($absentDays > 0) {
        $parts[] = (int) $absentDays . ' absent day(s)';
    }
    if ($halfDays > 0) {
        $parts[] = $halfDays . ' half-day(s)';
    }
    if ($unpaidLeaveDays > 0) {
        $parts[] = $unpaidLeaveDays . ' unpaid leave day(s)';
    }

    $summary['absent_days'] = $absentDays;
    $summary['half_days'] = $halfDays;
    $summary['unpaid_leave_days'] = $unpaidLeaveDays;
    $summary['unpaid_days'] = $unpaidDays;
    $summary['daily_rate'] = round($dailyRate, 2);
    $summary['deduction'] = $deduction;
    $summary['details'] = implode(', ', $parts);

    return $summary;
}

/**
 * Normalise an attendance-report date range and keep it chronological.
 *
 * @return array{0:string,1:string}
 */
function attendance_report_bounds($from, $to) {
    $from = trim((string) $from);
    $to = trim((string) $to);
    if (!is_valid_date_string($from)) {
        $from = date('Y-m-01');
    }
    if (!is_valid_date_string($to)) {
        $to = date('Y-m-d');
    }
    if ($to < $from) {
        $swap = $from;
        $from = $to;
        $to = $swap;
    }
    return [$from, $to];
}

/**
 * SQL predicate that is true for approved paid leave days.
 *
 * Approved annual, sick, casual and emergency leave count as present at work.
 * Only approved unpaid leave is an excused absence. Pass the attendance and
 * employee table aliases used by the calling query.
 */
function attendance_paid_leave_predicate($attendance = 'a', $employee = 'e') {
    return "(($attendance.status = 'leave') AND NOT EXISTS (
        SELECT 1 FROM leave_requests lr
        WHERE lr.employee_id = {$employee}.id
          AND lr.status = 'approved'
          AND {$attendance}.attendance_date BETWEEN lr.from_date AND lr.to_date
          AND LOWER(lr.leave_type) LIKE '%unpaid%'
    ))";
}

/**
 * Whether an attendance-report row is an approved paid leave day, which counts
 * as present at work. Unpaid leave and manual leave without a request stay
 * classified as leave.
 */
function attendance_leave_counts_as_present(array $row) {
    if ((string) ($row['status'] ?? '') !== 'leave') {
        return false;
    }
    $type = trim((string) ($row['leave_type'] ?? ''));
    if ($type === '') {
        // Fall back to the note written when leave is synced to the register.
        $type = (string) ($row['notes'] ?? '');
    }
    return stripos($type, 'unpaid') === false;
}

/**
 * Rows for the HR attendance report, joined to the employee record.
 */
function attendance_report_records($from, $to, $employeeId = 0, $department = '', $status = '') {
    global $pdo;
    [$from, $to] = attendance_report_bounds($from, $to);

    $sql = "SELECT a.id, a.employee_id, a.attendance_date, a.clock_in, a.clock_out,
                   a.working_hours, a.status, a.notes,
                   e.name AS employee_name, e.employee_code, e.department, e.designation,
                   (SELECT lr.leave_type FROM leave_requests lr
                     WHERE lr.employee_id = a.employee_id AND lr.status = 'approved'
                       AND a.attendance_date BETWEEN lr.from_date AND lr.to_date
                     ORDER BY lr.id DESC LIMIT 1) AS leave_type
            FROM attendance a
            JOIN employees e ON e.id = a.employee_id
            WHERE a.attendance_date BETWEEN ? AND ?
              AND (e.date_of_joining IS NULL OR a.attendance_date >= e.date_of_joining)";
    $params = [$from, $to];

    $employeeId = (int) $employeeId;
    if ($employeeId > 0) {
        $sql .= " AND a.employee_id = ?";
        $params[] = $employeeId;
    }

    $department = trim((string) $department);
    if ($department !== '') {
        $sql .= " AND e.department = ?";
        $params[] = $department;
    }

    $status = trim((string) $status);
    if (in_array($status, ['present', 'absent', 'half-day', 'leave', 'late'], true)) {
        $sql .= " AND a.status = ?";
        $params[] = $status;
    }

    $sql .= " ORDER BY a.attendance_date ASC, e.name ASC, a.id ASC";
    $stmt = $pdo->prepare($sql);
    $stmt->execute($params);
    return $stmt->fetchAll();
}

/**
 * Totals for the attendance report.
 */
function attendance_report_summary(array $records) {
    $summary = [
        'records' => 0,
        'employees' => 0,
        'present' => 0,
        'present_recorded' => 0,
        'paid_leave' => 0,
        'unpaid_leave' => 0,
        'absent' => 0,
        'half_day' => 0,
        'leave' => 0,
        'late' => 0,
        'hours' => 0.0,
    ];
    $employeeIds = [];
    foreach ($records as $row) {
        $summary['records']++;
        $status = (string) ($row['status'] ?? '');
        if ($status === 'present') {
            $summary['present']++;
            $summary['present_recorded']++;
        } elseif ($status === 'absent') {
            $summary['absent']++;
        } elseif ($status === 'half-day') {
            $summary['half_day']++;
        } elseif ($status === 'leave') {
            $summary['leave']++;
            // Approved paid leave counts as present at work.
            if (attendance_leave_counts_as_present($row)) {
                $summary['present']++;
                $summary['paid_leave']++;
            } else {
                $summary['unpaid_leave']++;
            }
        } elseif ($status === 'late') {
            $summary['late']++;
        }
        $summary['hours'] += (float) ($row['working_hours'] ?? 0);
        $employeeIds[(int) ($row['employee_id'] ?? 0)] = true;
    }
    $summary['employees'] = count($employeeIds);
    $summary['hours'] = round($summary['hours'], 2);
    return $summary;
}

/**
 * Per-employee totals for the attendance report.
 */
function attendance_report_employee_summary(array $records) {
    $rows = [];
    foreach ($records as $row) {
        $id = (int) ($row['employee_id'] ?? 0);
        if (!isset($rows[$id])) {
            $rows[$id] = [
                'employee_id' => $id,
                'employee_name' => (string) ($row['employee_name'] ?? ''),
                'employee_code' => (string) ($row['employee_code'] ?? ''),
                'department' => (string) ($row['department'] ?? ''),
                'records' => 0,
                'present' => 0,
                'present_recorded' => 0,
                'paid_leave' => 0,
                'unpaid_leave' => 0,
                'absent' => 0,
                'half_day' => 0,
                'leave' => 0,
                'late' => 0,
                'hours' => 0.0,
            ];
        }
        $rows[$id]['records']++;
        $status = (string) ($row['status'] ?? '');
        if ($status === 'present') {
            $rows[$id]['present']++;
            $rows[$id]['present_recorded']++;
        } elseif ($status === 'absent') {
            $rows[$id]['absent']++;
        } elseif ($status === 'half-day') {
            $rows[$id]['half_day']++;
        } elseif ($status === 'leave') {
            $rows[$id]['leave']++;
            // Approved paid leave counts as present at work.
            if (attendance_leave_counts_as_present($row)) {
                $rows[$id]['present']++;
                $rows[$id]['paid_leave']++;
            } else {
                $rows[$id]['unpaid_leave']++;
            }
        } elseif ($status === 'late') {
            $rows[$id]['late']++;
        }
        $rows[$id]['hours'] += (float) ($row['working_hours'] ?? 0);
    }
    foreach ($rows as &$row) {
        $row['hours'] = round($row['hours'], 2);
    }
    unset($row);
    usort($rows, function ($a, $b) {
        return strcasecmp($a['employee_name'], $b['employee_name']);
    });
    return $rows;
}

/**
 * Per-employee rows for the printable employee attendance sheet.
 *
 * Unrecorded days inside the period are treated as present (the daily register
 * is expected to be complete), while future days are ignored. Half-days count
 * as half present and half absent. Approved paid leave counts as present and is
 * never deducted; only approved unpaid leave reduces days present. A payroll
 * month counts at most 30 working days, so Pagume (month 13) days are excluded
 * when a 16–15 period crosses it.
 *
 * @return array<string,array<int,array>>
 */
function attendance_sheet_rows($from, $to, $department = '') {
    global $pdo;
    [$from, $to] = attendance_report_bounds($from, $to);
    $department = trim((string) $department);
    $today = date('Y-m-d');
    $effectiveTo = $to > $today ? $today : $to;

    // A payroll month is at most 30 working days. When the 16–15 period crosses
    // Pagume (month 13), the Pagume days are extra and are not counted.
    $pagumeStart = null;
    $pagumeEnd = null;
    $fromParts = ethiopian_date_parts($from);
    if ($fromParts !== null) {
        $fromYear = (int) $fromParts['year'];
        $fromMonth = (int) $fromParts['month'];
        if ($fromMonth === 12 || $fromMonth === 13) {
            $pagumeYear = $fromYear;
        } elseif ($fromMonth === 1) {
            $pagumeYear = $fromYear - 1;
        } else {
            $pagumeYear = null;
        }
        if ($pagumeYear !== null) {
            $pagumeStart = ethiopian_to_gregorian($pagumeYear, 13, 1);
            $meskeremFirst = ethiopian_to_gregorian($pagumeYear + 1, 1, 1);
            $pagumeEnd = date('Y-m-d', strtotime($meskeremFirst . ' -1 day'));
            if ($pagumeEnd < $from || $pagumeStart > $effectiveTo) {
                $pagumeStart = null;
                $pagumeEnd = null;
            }
        }
    }

    try {
        $sql = "SELECT id, name, employee_code, department, date_of_joining
                FROM employees
                WHERE status = 1 AND (date_of_joining IS NULL OR date_of_joining <= ?)";
        $params = [$effectiveTo];
        if ($department !== '') {
            $sql .= " AND department = ?";
            $params[] = $department;
        }
        $sql .= " ORDER BY department IS NULL, department ASC, name ASC";
        $stmt = $pdo->prepare($sql);
        $stmt->execute($params);
        $employees = $stmt->fetchAll();
        if (!$employees) {
            return [];
        }

        $ids = array_values(array_unique(array_map('intval', array_column($employees, 'id'))));
        $placeholders = implode(',', array_fill(0, count($ids), '?'));

        $stats = [];
        $pagumeFilter = '';
        $periodParams = [$from, $to];
        if ($pagumeStart !== null && $pagumeEnd !== null) {
            $pagumeFilter = " AND (a.attendance_date < ? OR a.attendance_date > ?)";
            $periodParams[] = $pagumeStart;
            $periodParams[] = $pagumeEnd;
        }
        $stmt = $pdo->prepare(
            "SELECT a.employee_id,
                    SUM(CASE WHEN a.status = 'present' THEN 1 ELSE 0 END) AS present_days,
                    SUM(CASE WHEN a.status = 'half-day' THEN 1 ELSE 0 END) AS half_days,
                    SUM(CASE WHEN a.status = 'absent' THEN 1 ELSE 0 END) AS absent_days,
                    SUM(CASE WHEN a.status = 'leave' THEN 1 ELSE 0 END) AS leave_days,
                    SUM(CASE WHEN a.status = 'late' THEN 1 ELSE 0 END) AS late_days
             FROM attendance a
             JOIN employees e ON e.id = a.employee_id
             WHERE a.attendance_date BETWEEN ? AND ?$pagumeFilter
               AND (a.attendance_date <= ? OR a.status <> 'leave')
               AND (e.date_of_joining IS NULL OR a.attendance_date >= e.date_of_joining)
               AND a.employee_id IN ($placeholders)
             GROUP BY a.employee_id"
        );
        $stmt->execute(array_merge($periodParams, [$effectiveTo], $ids));
        foreach ($stmt->fetchAll() as $row) {
            $stats[(int) $row['employee_id']] = $row;
        }

        // Every saved register row in the period. The dates are used to count a
        // future day that HR has already filled in (for example tomorrow's
        // register), while unrecorded future days stay ignored. Late minutes are
        // summed here as well, from each late day's recorded clock-in.
        $lateMinutes = [];
        $savedDates = [];
        $stmt = $pdo->prepare(
            "SELECT a.employee_id, a.attendance_date, a.status, a.clock_in, a.shift
             FROM attendance a
             JOIN employees e ON e.id = a.employee_id
             WHERE a.attendance_date BETWEEN ? AND ?$pagumeFilter
               AND a.status <> 'leave'
               AND (e.date_of_joining IS NULL OR a.attendance_date >= e.date_of_joining)
               AND a.employee_id IN ($placeholders)"
        );
        $stmt->execute(array_merge($periodParams, $ids));
        foreach ($stmt->fetchAll() as $row) {
            $eid = (int) $row['employee_id'];
            $savedDates[$eid][(string) $row['attendance_date']] = true;
            if (strtolower((string) $row['status']) === 'late') {
                $lateMinutes[$eid] = ($lateMinutes[$eid] ?? 0) + attendance_late_minutes(
                    $row['clock_in'] ?? '',
                    $row['shift'] ?? 'morning',
                    (string) $row['attendance_date']
                );
            }
        }

        // Approved leave is split into paid and unpaid. Paid leave counts as
        // present at work and is not deducted; only unpaid leave is excused
        // absence. Pagume days are skipped here as well.
        $leaveInfo = [];
        $unpaidDates = [];
        $unpaidTypes = [];
        $stmt = $pdo->prepare(
            "SELECT lr.employee_id, lr.leave_type, lr.from_date, lr.to_date
             FROM leave_requests lr
             WHERE lr.status = 'approved'
               AND lr.from_date <= ? AND lr.to_date >= ?
               AND lr.employee_id IN ($placeholders)
             ORDER BY lr.from_date"
        );
        $stmt->execute(array_merge([$effectiveTo, $from], $ids));
        foreach ($stmt->fetchAll() as $row) {
            $eid = (int) $row['employee_id'];
            $type = trim((string) $row['leave_type']);
            $isUnpaid = stripos($type, 'unpaid') !== false;

            $cursor = max(strtotime((string) $row['from_date']), strtotime($from));
            $last = min(strtotime((string) $row['to_date']), strtotime($effectiveTo));
            $days = 0;
            while ($cursor !== false && $cursor <= $last) {
                $day = date('Y-m-d', $cursor);
                $cursor = strtotime('+1 day', $cursor);
                if ($pagumeStart !== null && $pagumeEnd !== null
                    && $day >= $pagumeStart && $day <= $pagumeEnd) {
                    continue;
                }
                $days++;
                if ($isUnpaid) {
                    $unpaidDates[$eid][$day] = true;
                }
            }
            if ($days <= 0) {
                continue;
            }
            if (!isset($leaveInfo[$eid])) {
                $leaveInfo[$eid] = ['days' => 0, 'types' => []];
            }
            $leaveInfo[$eid]['days'] += $days;
            if ($type !== '' && !in_array($type, $leaveInfo[$eid]['types'], true)) {
                $leaveInfo[$eid]['types'][] = $type;
            }
            if ($isUnpaid && $type !== '' && !in_array($type, $unpaidTypes[$eid] ?? [], true)) {
                $unpaidTypes[$eid][] = $type;
            }
        }

        // Never count the same day twice: skip unpaid-leave dates that the
        // register already flags as absent or half-day.
        if ($unpaidDates) {
            $stmt = $pdo->prepare(
                "SELECT employee_id, attendance_date, status FROM attendance
                 WHERE status IN ('absent', 'half-day') AND attendance_date BETWEEN ? AND ?"
            );
            $stmt->execute([$from, $effectiveTo]);
            foreach ($stmt->fetchAll() as $row) {
                $eid = (int) $row['employee_id'];
                $day = (string) $row['attendance_date'];
                if (isset($unpaidDates[$eid][$day])) {
                    unset($unpaidDates[$eid][$day]);
                }
            }
        }

        $groups = [];
        foreach ($employees as $employee) {
            $eid = (int) $employee['id'];
            $agg = $stats[$eid] ?? [];
            $halfDays = (float) ($agg['half_days'] ?? 0);
            $absentDays = (float) ($agg['absent_days'] ?? 0) + $halfDays * 0.5;
            $recordedLeaveDays = max(0, (float) ($agg['leave_days'] ?? 0));
            $approvedLeaveDays = max(0, (float) ($leaveInfo[$eid]['days'] ?? 0));
            $leaveDays = max($recordedLeaveDays, $approvedLeaveDays);
            // Paid approved leave counts as present. Only unpaid leave is an
            // excused absence and is the only leave that reduces present days.
            $unpaidLeaveDays = min((float) count($unpaidDates[$eid] ?? []), $leaveDays);

            $periodStart = $from;
            $joining = (string) ($employee['date_of_joining'] ?? '');
            if ($joining !== '' && $joining > $periodStart) {
                $periodStart = $joining;
            }
            // Past days count as present even when they were not recorded. A
            // future day counts only when the register already has a saved row
            // for it, so a pre-filled tomorrow is reflected straight away.
            $employeeDays = 0;
            if ($periodStart <= $to) {
                $cursor = strtotime($periodStart);
                $end = strtotime($to);
                while ($cursor !== false && $cursor <= $end) {
                    $day = date('Y-m-d', $cursor);
                    $cursor = strtotime('+1 day', $cursor);
                    if ($pagumeStart !== null && $pagumeEnd !== null
                        && $day >= $pagumeStart && $day <= $pagumeEnd) {
                        continue;
                    }
                    if ($day <= $today || isset($savedDates[$eid][$day])) {
                        $employeeDays++;
                    }
                }
            }
            $employeeDays = min(30, max(0, $employeeDays));
            // Late time reduces the days present: 8 working hours = 1 day.
            // Example: 4:00 late in the period removes 0.5 from the day count.
            $lateMinutesTotal = max(0, (int) ($lateMinutes[$eid] ?? 0));
            $lateDayEquivalent = $lateMinutesTotal / 480;
            $presentDays = max(0, $employeeDays - $absentDays - $unpaidLeaveDays - $lateDayEquivalent);
            $presentDays = round($presentDays, 2);

            $departmentName = trim((string) ($employee['department'] ?? ''));
            if ($departmentName === '') {
                $departmentName = 'ያልተመደበ';
            }

            $groups[$departmentName][] = [
                'name' => (string) $employee['name'],
                'employee_code' => (string) $employee['employee_code'],
                'department' => $departmentName,
                'present_days' => $presentDays,
                'absent_days' => $absentDays,
                'leave_hours' => $leaveDays * 8,
                'leave_days' => $leaveDays,
                'unpaid_leave_days' => $unpaidLeaveDays,
                'late_days' => max(0, (int) ($agg['late_days'] ?? 0)),
                'late_minutes' => $lateMinutesTotal,
                'late_hours' => round($lateMinutesTotal / 60, 2),
                'late_day_equivalent' => round($lateDayEquivalent, 2),
                'reason' => implode(', ', $leaveInfo[$eid]['types'] ?? []),
            ];
        }

        return $groups;
    } catch (Throwable $e) {
        return [];
    }
}

/**
 * Localized label for an attendance status.
 */
function attendance_status_label($status) {
    $map = [
        'present' => 'attendance_report_present',
        'absent' => 'attendance_report_absent',
        'half-day' => 'attendance_report_half_day',
        'leave' => 'attendance_report_leave',
        'late' => 'attendance_report_late',
