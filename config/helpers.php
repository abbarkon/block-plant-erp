/**
 * Validate one uploaded evidence file.
 *
 * @return array{ok:bool,error?:string,extension?:string,mime?:string,size?:int,original_name?:string}
 */
function validate_warning_evidence_upload($file) {
    $maxBytes = 10 * 1024 * 1024;
    if (!is_array($file) || ($file['error'] ?? UPLOAD_ERR_NO_FILE) === UPLOAD_ERR_NO_FILE) {
        return ['ok' => false, 'error' => 'Choose a file to attach.'];
    }
    if (($file['error'] ?? UPLOAD_ERR_OK) !== UPLOAD_ERR_OK) {
        return ['ok' => false, 'error' => 'The upload failed. The file may be larger than the server limit.'];
    }
    $tmpName = (string) ($file['tmp_name'] ?? '');
    if ($tmpName === '' || !is_uploaded_file($tmpName)) {
        return ['ok' => false, 'error' => 'The upload could not be verified.'];
    }
    $size = (int) ($file['size'] ?? 0);
    if ($size <= 0 || $size > $maxBytes) {
        return ['ok' => false, 'error' => 'Each evidence file must be between 1 byte and 10 MB.'];
    }
    $originalName = basename(str_replace('\\', '/', (string) ($file['name'] ?? 'evidence')));
    $extension = strtolower(pathinfo($originalName, PATHINFO_EXTENSION));
    $allowed = warning_evidence_allowed_types();
    if (!isset($allowed[$extension])) {
        return ['ok' => false, 'error' => 'Allowed evidence file types: PDF, JPG, JPEG, PNG, WEBP, DOC, DOCX.'];
    }
    $mime = '';
    if (class_exists('finfo')) {
        $finfo = new finfo(FILEINFO_MIME_TYPE);
        $mime = (string) $finfo->file($tmpName);
    }
    if ($mime !== '' && !in_array($mime, $allowed[$extension], true)) {
        return ['ok' => false, 'error' => 'The evidence file content does not match its extension.'];
    }
    return [
        'ok' => true,
        'extension' => $extension,
        'mime' => $mime !== '' ? $mime : 'application/octet-stream',
        'size' => $size,
        'original_name' => mb_substr($originalName, 0, 255),
    ];
}

/**
 * Move one validated evidence upload into per-revocation storage and record it.
 *
 * @return array{ok:bool,error?:string,id?:int,name?:string}
 */
function store_attendance_warning_evidence($revocationId, $file, $userId) {
    global $pdo;
    $revocationId = (int) $revocationId;
    if ($revocationId <= 0) {
        return ['ok' => false, 'error' => 'The warning revocation could not be found.'];
    }
    $validation = validate_warning_evidence_upload($file);
    if (!$validation['ok']) {
        return $validation;
    }
    $dir = warning_evidence_upload_dir($revocationId);
    if ($dir === '' || !is_dir($dir)) {
        return ['ok' => false, 'error' => 'The evidence folder could not be created. Check upload permissions.'];
    }
    $storedName = bin2hex(random_bytes(16)) . '.' . $validation['extension'];
    $target = $dir . DIRECTORY_SEPARATOR . $storedName;
    if (!move_uploaded_file((string) $file['tmp_name'], $target)) {
        return ['ok' => false, 'error' => 'The evidence file could not be saved.'];
    }
    @chmod($target, 0640);
    try {
        $stmt = $pdo->prepare(
            "INSERT INTO attendance_warning_revocation_files
                (revocation_id, original_name, stored_name, file_path, file_size, mime_type, uploaded_by)
             VALUES (?, ?, ?, ?, ?, ?, ?)"
        );
        $stmt->execute([
            $revocationId,
            $validation['original_name'],
            $storedName,
            'uploads/warning_evidence/' . $revocationId . '/' . $storedName,
            $validation['size'],
            $validation['mime'],
            (int) $userId > 0 ? (int) $userId : null,
        ]);
        return ['ok' => true, 'id' => (int) $pdo->lastInsertId(), 'name' => $validation['original_name']];
    } catch (Throwable $e) {
        @unlink($target);
        return ['ok' => false, 'error' => 'The evidence record could not be saved.'];
    }
}

