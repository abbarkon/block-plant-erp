function post_accounting_journal($entryNo, $entryDate, $description, $reference, array $lines, $userId) {
    global $pdo;
    $existing = $pdo->prepare("SELECT id FROM journal_entries WHERE entry_no = ?");
    $existing->execute([$entryNo]);
    if ($existing->fetchColumn()) {
        return false;
    }

    $validLines = [];
    $totalDebit = 0.0;
    $totalCredit = 0.0;
    foreach ($lines as $line) {
        [$accountCode, $debit, $credit, $lineDescription] = $line;
        $debit = round((float) $debit, 2);
        $credit = round((float) $credit, 2);
        if ($debit < 0 || $credit < 0 || ($debit > 0 && $credit > 0)) {
            throw new InvalidArgumentException('Journal lines must contain a non-negative debit or credit, not both.');
        }
        if ($debit == 0.0 && $credit == 0.0) {
            continue;
        }
        $accountStmt = $pdo->prepare("SELECT id, account_type FROM chart_of_accounts WHERE account_code = ? AND status = 1 FOR UPDATE");
        $accountStmt->execute([(string) $accountCode]);
        $account = $accountStmt->fetch();
        if (!$account) {
            throw new RuntimeException('Required chart-of-accounts code is missing or inactive: ' . $accountCode);
        }
        $validLines[] = [(int) $account['id'], $account['account_type'], $debit, $credit, $lineDescription];
        $totalDebit += $debit;
        $totalCredit += $credit;
    }
    if (count($validLines) < 2 || abs($totalDebit - $totalCredit) > 0.009) {
        throw new InvalidArgumentException('Journal entry must have at least two lines and equal total debits and credits.');
    }

    $entryStmt = $pdo->prepare("INSERT INTO journal_entries(entry_no,entry_date,description,reference_no,total_debit,total_credit,status,posted_by,posted_at,created_by) VALUES(?,?,?,?,?,?,'posted',?,NOW(),?)");
    $entryStmt->execute([$entryNo, $entryDate, $description, $reference, round($totalDebit, 2), round($totalCredit, 2), $userId, $userId]);
    $entryId = (int) $pdo->lastInsertId();
    $lineStmt = $pdo->prepare("INSERT INTO journal_entry_lines(entry_id,account_id,debit,credit,description) VALUES(?,?,?,?,?)");
    $balanceStmt = $pdo->prepare("UPDATE chart_of_accounts SET balance = balance + ? WHERE id = ?");
    foreach ($validLines as [$accountId, $accountType, $debit, $credit, $lineDescription]) {
        $lineStmt->execute([$entryId, $accountId, $debit, $credit, $lineDescription]);
        $normalDebit = in_array(strtolower($accountType), ['asset', 'expense'], true);
        $balanceDelta = $normalDebit ? $debit - $credit : $credit - $debit;
        $balanceStmt->execute([$balanceDelta, $accountId]);
    }
    return $entryId;
}

/**
 * Make sure the two accounts a payroll journal entry needs in order to balance
 * exist in the chart of accounts: the receivable reduced by loan recovery, and
 * the liability holding deductions withheld from gross pay.
 *
 * Purely additive and idempotent - existing codes are reused, and a chart that
 * cannot be extended safely falls back to Accounts Payable so posting never
 * hard-fails on account setup.
 *
 * @return array{loan:string, deductions:string} account codes
 */
function ensure_payroll_journal_accounts() {
    global $pdo;
    static $accounts = null;
    if ($accounts !== null) {
        return $accounts;
    }

    $wanted = [
        'loan'       => ['1160', 'Employee Loans Receivable', 'asset'],
        'deductions' => ['2180', 'Payroll Deductions Payable', 'liability'],
    ];
    $result = ['loan' => '2110', 'deductions' => '2110'];

    foreach ($wanted as $key => $account) {
        [$code, $name, $type] = $account;
        $stmt = $pdo->prepare("SELECT account_code FROM chart_of_accounts WHERE account_code = ? AND status = 1");
        $stmt->execute([(string) $code]);
        $existing = $stmt->fetchColumn();
        if ($existing) {
            $result[$key] = (string) $existing;
            continue;
        }
        try {
            $insert = $pdo->prepare("INSERT INTO chart_of_accounts(account_code, account_name, account_type, parent_id, balance, status) VALUES(?,?,?,NULL,0,1)");
            $insert->execute([(string) $code, $name, $type]);
            $result[$key] = (string) $code;
        } catch (PDOException $e) {
            $result[$key] = '2110';
        }
    }

    $accounts = $result;
    return $accounts;
}

/**
 * Totals needed to book one period of payroll as a single journal entry.
 *
 * Returns gross pay, withheld deductions, loan recovery actually applied
 * through payroll and the resulting net pay for a month/year. An empty array
 * means there is no payroll recorded for that period.
 */
function payroll_period_totals($month, $year) {
    global $pdo;
    $stmt = $pdo->prepare(
        "SELECT COUNT(*) AS employees,
                COALESCE(SUM(p.basic_salary), 0) AS basic,
                COALESCE(SUM(p.allowances), 0) AS allowances,
                COALESCE(SUM(p.overtime_payment), 0) AS overtime,
                COALESCE(SUM(p.deductions), 0) AS deductions,
                COALESCE(SUM(p.net_salary), 0) AS net
         FROM payroll p
         WHERE p.month = ? AND p.year = ?"
    );
    $stmt->execute([(int) $month, (int) $year]);
    $row = $stmt->fetch();
    if (!$row || (int) $row['employees'] === 0) {
        return [];
    }

    $loanRecovery = 0.0;
    try {
        $loanStmt = $pdo->prepare(
            "SELECT COALESCE(SUM(lr.amount_deducted), 0)
             FROM loan_repayments lr
             WHERE lr.payroll_month = ? AND lr.payroll_year = ? AND lr.source = 'payroll'"
        );
        $loanStmt->execute([(int) $month, (int) $year]);
        $loanRecovery = (float) $loanStmt->fetchColumn();
    } catch (PDOException $e) {
        $loanRecovery = 0.0;
    }

    $gross = (float) $row['basic'] + (float) $row['allowances'] + (float) $row['overtime'];
    $net = (float) $row['net'];
    // Deductions are reconciled off the stored gross so the entry always balances.
    $deductions = round($gross - $net, 2);
    if ($loanRecovery > $deductions) {
        $loanRecovery = max(0.0, $deductions);
    }

    return [
        'employees' => (int) $row['employees'],
        'basic' => (float) $row['basic'],
        'allowances' => (float) $row['allowances'],
        'overtime' => (float) $row['overtime'],
        'gross' => round($gross, 2),
        'deductions' => $deductions,
        'loan' => round($loanRecovery, 2),
        'other' => round($deductions - $loanRecovery, 2),
        'net' => round($net, 2),
    ];
}

/**
 * Check if user has permission
 */
function has_permission($module, $action = 'view') {
    if (!isset($_SESSION['user_id'])) {
        return false;
    }
    $allowed = ['view' => 'can_view', 'create' => 'can_create', 'edit' => 'can_edit', 'delete' => 'can_delete', 'approve' => 'can_approve'];
    if (!isset($allowed[$action])) {
        return false;
    }
    global $pdo;
    try {
        ensure_department_access_schema();
        $userStmt = $pdo->prepare("SELECT role, department, department_role FROM users WHERE id = ? AND status = 1");
        $userStmt->execute([$_SESSION['user_id']]);
        $user = $userStmt->fetch();
        if (!$user) {
            return false;
        }
        $userRole = strtolower(trim((string) $user['role']));
        $_SESSION['role'] = $userRole;
        if (in_array($userRole, ['admin', 'administrator'], true)) {
            return true;
        }
        if ($module === 'dashboard' && $action === 'view') {
            return $userRole !== '';
        }
        // A user may belong to several departments (primary + extra ones added in User Management).
        $assignments = user_department_assignments((int) $_SESSION['user_id'], $user);
        if ($assignments) {
            $col = $allowed[$action];
            foreach ($assignments as $assignment) {
                $departmentModules = department_permission_modules()[$assignment['department']] ?? [];
                if (!in_array($module, $departmentModules, true)) {
                    continue;
                }
                if ($assignment['role'] === 'manager') {
                    return true;
                }
                // Department users always keep their baseline view/create access.
                if (in_array($action, ['view', 'create'], true)) {
                    return true;
                }
                // HR managers can grant extra actions (edit/delete/approve) from HR > Permissions.
                ensure_hr_permission_schema();
                $stmt = $pdo->prepare("SELECT {$col} FROM hr_permission_grants WHERE user_id = ?");
                $stmt->execute([(int) $_SESSION['user_id']]);
                $row = $stmt->fetch();
                if ($row && (int) $row[$col] === 1) {
                    return true;
                }
            }
            return false;
        }
        ensure_user_permission_defaults((int) $_SESSION['user_id']);
        $col = $allowed[$action];
        $stmt = $pdo->prepare("SELECT {$col} FROM user_permissions WHERE user_id = ? AND module = ?");
        $stmt->execute([$_SESSION['user_id'], $module]);
        $row = $stmt->fetch();
        return $row && (int) $row[$col] === 1;
    } catch (PDOException $e) {
        return false;
    }
}

/**
 * HR managers (and custom non-department users with HR edit access) may grant
 * extra HR actions to HR users. Regular HR users must never reach this screen:
