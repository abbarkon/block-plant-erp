/**
 * Convert a Gregorian date to a Julian Day Number.
 */
function gregorian_to_jdn($year, $month, $day) {
    $a = intdiv(14 - (int) $month, 12);
    $y = (int) $year + 4800 - $a;
    $m = (int) $month + 12 * $a - 3;
    return (int) $day + intdiv(153 * $m + 2, 5) + 365 * $y
        + intdiv($y, 4) - intdiv($y, 100) + intdiv($y, 400) - 32045;
}

/**
 * Convert a Gregorian date to Ethiopian calendar parts.
 *
 * @return array{year:int,month:int,day:int}|null
 */
function ethiopian_date_parts($date) {
    $timestamp = strtotime((string) $date);
    if ($timestamp === false) {
        return null;
    }

    $jd = gregorian_to_jdn((int) date('Y', $timestamp), (int) date('n', $timestamp), (int) date('j', $timestamp));
    $epoch = 1723856;
    $delta = $jd - $epoch;
    $r = $delta % 1461;
    if ($r < 0) {
        $r += 1461;
    }
    $n = ($r % 365) + 365 * intdiv($r, 1460);
    $year = 4 * intdiv($delta - $r, 1461) + intdiv($r, 365) - intdiv($r, 1460);
    $month = intdiv($n, 30) + 1;
    $day = ($n % 30) + 1;

    return ['year' => $year, 'month' => $month, 'day' => $day];
}

/**
 * Format a Gregorian date in the Ethiopian calendar using Amharic month names.
 */
function format_ethiopian_date($date, $includeWeekday = false) {
    $timestamp = strtotime((string) $date);
    $parts = ethiopian_date_parts($date);
    if ($timestamp === false || $parts === null) {
        return '';
    }

    $months = [
        1 => 'መስከረም',
        2 => 'ጥቅምት',
        3 => 'ኅዳር',
        4 => 'ታኅሣሥ',
        5 => 'ጥር',
        6 => 'የካቲት',
        7 => 'መጋቢት',
        8 => 'ሚያዝያ',
        9 => 'ግንቦት',
        10 => 'ሰኔ',
        11 => 'ሐምሌ',
        12 => 'ነሐሴ',
        13 => 'ጳጉሜ',
    ];
    $weekdays = ['እሁድ', 'ሰኞ', 'ማክሰኞ', 'ረቡዕ', 'ሐሙስ', 'ዓርብ', 'ቅዳሜ'];

    $dateLabel = str_pad((string) $parts['day'], 2, '0', STR_PAD_LEFT)
        . ' ' . $months[$parts['month']]
        . ' ' . $parts['year'] . ' ዓ.ም.';

    return $includeWeekday ? $weekdays[(int) date('w', $timestamp)] . ', ' . $dateLabel : $dateLabel;
}

/**
 * Convert a Julian Day Number back to a Gregorian date (YYYY-MM-DD).
 */
function jdn_to_gregorian($jd) {
    $a = (int) $jd + 32044;
    $b = intdiv(4 * $a + 3, 146097);
    $c = $a - intdiv(146097 * $b, 4);
    $d = intdiv(4 * $c + 3, 1461);
    $e = $c - intdiv(1461 * $d, 4);
    $m = intdiv(5 * $e + 2, 153);
    $day = $e - intdiv(153 * $m + 2, 5) + 1;
    $month = $m + 3 - 12 * intdiv($m, 10);
    $year = 100 * $b + $d - 4800 + intdiv($m, 10);
    return sprintf('%04d-%02d-%02d', $year, $month, $day);
}

/**
 * Convert an Ethiopian calendar date to a Julian Day Number.
 */
function ethiopian_to_jdn($year, $month, $day) {
    return 1723856 + 365 * (int) $year + intdiv((int) $year, 4)
        + 30 * ((int) $month - 1) + ((int) $day - 1);
}

/**
 * Convert an Ethiopian calendar date to a Gregorian date (YYYY-MM-DD).
 */
function ethiopian_to_gregorian($year, $month, $day) {
    return jdn_to_gregorian(ethiopian_to_jdn($year, $month, $day));
}

/**
 * Short Ethiopian date used on printed forms, e.g. 16/03/17.
 */
function format_ethiopian_short_date($date) {
    $parts = ethiopian_date_parts($date);
    if ($parts === null) {
        return '';
    }
    return sprintf('%02d/%02d/%02d', $parts['day'], $parts['month'], $parts['year'] % 100);
}

/**
 * Shift an Ethiopian year/month by a number of months.
 *
 * @return array{0:int,1:int}
 */
function ethiopian_month_shift($year, $month, $delta) {
    $index = ((int) $year - 1) * 12 + ((int) $month - 1) + (int) $delta;
    $newYear = intdiv($index, 12) + 1;
    $newMonth = (($index % 12) + 12) % 12 + 1;
    return [$newYear, $newMonth];
}

/**
 * Ethiopian payroll period (16th of one month to the 15th of the next).
 * Offset 0 is the period containing today, -1 is the previous period.
 *
 * The period that crosses Pagume (month 13) runs from 16 Nehase to
 * 15 Meskerem, so it is longer than 30 days.
 *
 * @return array{0:string,1:string} Gregorian start and end dates.
 */
function ethiopian_payroll_period($offset = 0) {
    $parts = ethiopian_date_parts(date('Y-m-d'));
    if ($parts === null) {
        return [date('Y-m-01'), date('Y-m-t')];
    }

    $year = (int) $parts['year'];
    $month = (int) $parts['month'];
    $day = (int) $parts['day'];

    if ($month === 13) {
        // Pagume belongs to the period that started on 16 Nehase.
        $startYear = $year;
        $startMonth = 12;
    } elseif ($day >= 16) {
        $startYear = $year;
        $startMonth = $month;
    } elseif ($month === 1) {
        $startYear = $year - 1;
        $startMonth = 12;
    } else {
        $startYear = $year;
        $startMonth = $month - 1;
    }

    if ((int) $offset !== 0) {
        [$startYear, $startMonth] = ethiopian_month_shift($startYear, $startMonth, (int) $offset);
    }

    if ($startMonth === 12) {
        $endYear = $startYear + 1;
        $endMonth = 1;
    } else {
        $endYear = $startYear;
        $endMonth = $startMonth + 1;
    }

    return [
        ethiopian_to_gregorian($startYear, $startMonth, 16),
        ethiopian_to_gregorian($endYear, $endMonth, 15),
    ];
}

/**
 * Format date in readable format.
 *
 * English uses the Gregorian calendar; Amharic uses the Ethiopian calendar.
 */
function format_app_date($date, $includeWeekday = false) {
    $timestamp = strtotime((string) $date);
    if ($timestamp === false) {
        return '';
    }
    if (app_lang() !== 'am') {
        return $includeWeekday ? date('l, d F Y', $timestamp) : date('d M Y', $timestamp);
    }

    return format_ethiopian_date($date, $includeWeekday);
}

function format_app_month_name($month) {
    $month = max(1, min(12, (int) $month));
    if (app_lang() !== 'am') {
        return date('F', mktime(0, 0, 0, $month, 1));
    }
    $months = ['ጃንዩወሪ', 'ፌብሩወሪ', 'ማርች', 'ኤፕሪል', 'ሜይ', 'ጁን', 'ጁላይ', 'ኦገስት', 'ሴፕቴምበር', 'ኦክቶበር', 'ኖቬምበር', 'ዲሴምበር'];
    return $months[$month - 1];
}

function format_app_month_year($month, $year) {
    $month = max(1, min(12, (int) $month));
    $year = (int) $year;
    return format_app_month_name($month) . ' ' . $year;
}

function format_date($date) {
    return format_app_date($date);
}

