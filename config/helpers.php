/**
 * Create the warning-revocation and warning-issue tables when an existing
 * installation has not run the updated database.sql yet.
 *
 * attendance_warning_issues records the first time a warning letter is
 * generated so HR and the employee are notified exactly once per warning.
 */
function ensure_attendance_warning_schema() {
    global $pdo;
    static $done = false;
    if ($done) {
        return;
    }
    try {
        $pdo->exec(
            "CREATE TABLE IF NOT EXISTS attendance_warning_revocations (
                id INT AUTO_INCREMENT PRIMARY KEY,
                employee_id INT NOT NULL,
                period_from DATE NOT NULL,
                period_to DATE NOT NULL,
                reason TEXT NOT NULL,
                evidence_reference VARCHAR(255) DEFAULT NULL,
                revoked_by INT DEFAULT NULL,
                revoked_at DATETIME NOT NULL,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                UNIQUE KEY unique_warning_revocation (employee_id, period_from, period_to),
                FOREIGN KEY (employee_id) REFERENCES employees(id),
                FOREIGN KEY (revoked_by) REFERENCES users(id)
            ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4"
        );
        $pdo->exec(
            "CREATE TABLE IF NOT EXISTS attendance_warning_revocation_files (
                id INT AUTO_INCREMENT PRIMARY KEY,
                revocation_id INT NOT NULL,
                original_name VARCHAR(255) NOT NULL,
                stored_name VARCHAR(255) NOT NULL,
                file_path VARCHAR(500) NOT NULL,
                file_size INT NOT NULL DEFAULT 0,
                mime_type VARCHAR(120) NOT NULL,
                uploaded_by INT DEFAULT NULL,
                uploaded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                FOREIGN KEY (revocation_id) REFERENCES attendance_warning_revocations(id) ON DELETE CASCADE,
                FOREIGN KEY (uploaded_by) REFERENCES users(id)
            ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4"
        );
        $pdo->exec(
            "CREATE TABLE IF NOT EXISTS attendance_warning_issues (
                id INT AUTO_INCREMENT PRIMARY KEY,
                employee_id INT NOT NULL,
                period_from DATE NOT NULL,
                period_to DATE NOT NULL,
                absence_hash CHAR(32) NOT NULL,
                absence_days INT NOT NULL DEFAULT 0,
                reference VARCHAR(80) NOT NULL,
                issued_by INT DEFAULT NULL,
                issued_at DATETIME NOT NULL,
                notified_count INT NOT NULL DEFAULT 0,
                UNIQUE KEY unique_warning_issue (employee_id, absence_hash),
                KEY idx_warning_issue_reference (reference),
                FOREIGN KEY (employee_id) REFERENCES employees(id),
                FOREIGN KEY (issued_by) REFERENCES users(id)
            ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4"
        );
        $done = true;
    } catch (Throwable $e) {
        // Leave the flag unset so a transient database error can be retried.
    }
}

/**
 * Base directory for evidence documents attached to warning revocations.
 * Files are served through the HR download endpoint, not linked directly.
 */
function warning_evidence_base_dir($create = false) {
    $base = dirname(__DIR__) . '/uploads/warning_evidence';
    if (!is_dir($base)) {
        if (!$create) {
            return $base;
        }
        if (!@mkdir($base, 0755, true) && !is_dir($base)) {
            return '';
        }
    }
    $htaccess = $base . '/.htaccess';
    if (!is_file($htaccess)) {
        @file_put_contents($htaccess, "Require all denied\nOptions -Indexes\n");
    }
    $index = $base . '/index.html';
    if (!is_file($index)) {
        @file_put_contents($index, '');
    }
    return $base;
}

