}

/**
 * Map an employee-return condition to the fixed-asset condition vocabulary.
 */
function asset_return_condition_to_asset_status($condition) {
    $condition = strtolower(trim((string) $condition));
    if (in_array($condition, ['excellent', 'good'], true)) {
        return 'good';
    }
    if ($condition === 'fair') {
        return 'fair';
    }
    if (in_array($condition, ['poor', 'needs repair'], true)) {
        return 'poor';
    }
    if ($condition === 'damaged') {
        return 'damaged';
    }
    return 'critical';
}

/**
 * Add the optional columns used by asset-return maintenance requests.
 * Idempotent and safe on installations with an older maintenance table.
 */
function ensure_asset_return_schema() {
    global $pdo;
    static $checked = false;
    if ($checked) {
        return;
    }
    $checked = true;

    try {
        $columnInfo = $pdo->query("SHOW COLUMNS FROM asset_maintenance")->fetchAll();
        $columns = array_column($columnInfo, 'Field');
    } catch (Throwable $e) {
        return;
    }

    $assetIdNullable = false;
    foreach ($columnInfo as $column) {
        if ($column['Field'] === 'asset_id' && strtoupper((string) $column['Null']) === 'YES') {
            $assetIdNullable = true;
            break;
        }
    }

    $wanted = [
        'source' => "VARCHAR(50) DEFAULT 'manual'",
        'employee_asset_id' => 'INT NULL',
        'status' => "VARCHAR(20) NOT NULL DEFAULT 'completed'",
        'priority' => "VARCHAR(20) NOT NULL DEFAULT 'normal'",
        'assigned_to' => 'INT NULL',
        'due_date' => 'DATE NULL',
        'completed_at' => 'DATETIME NULL',
        'completion_notes' => 'TEXT NULL',
    ];
    foreach ($wanted as $column => $definition) {
        if (!in_array($column, $columns, true)) {
            try {
                $pdo->exec("ALTER TABLE asset_maintenance ADD COLUMN {$column} {$definition}");
            } catch (Throwable $ignored) {
            }
        }
    }
    if (!$assetIdNullable) {
        try {
            $pdo->exec("ALTER TABLE asset_maintenance MODIFY asset_id INT NULL");
        } catch (Throwable $ignored) {
        }
    }
}

/**
 * Find an open maintenance request (pending/in_progress) for a serial number.
 * Matches either the employee-asset record linked to the request or a fixed
 * asset with that asset code. Used to stop an asset being reissued while it
 * is still waiting for repair.
 *
 * @return int|null Maintenance request id, or null when none is open.
 */
function open_maintenance_request_for_serial($serialNumber, $excludeMaintenanceId = null) {
    global $pdo;

    $serialNumber = trim((string) $serialNumber);
    if ($serialNumber === '') {
        return null;
    }

    ensure_asset_return_schema();

    try {
        $sql = "SELECT am.id
                FROM asset_maintenance am
                LEFT JOIN employee_assets ea ON ea.id = am.employee_asset_id
                LEFT JOIN assets a ON a.id = am.asset_id
                WHERE am.status IN ('pending', 'in_progress')
                  AND (ea.serial_number = ? OR a.asset_code = ?)";
        $params = [$serialNumber, $serialNumber];
        if ($excludeMaintenanceId !== null) {
            $sql .= " AND am.id <> ?";
            $params[] = (int) $excludeMaintenanceId;
        }
        $sql .= " LIMIT 1";
        $stmt = $pdo->prepare($sql);
        $stmt->execute($params);
        $id = $stmt->fetchColumn();
        return $id ? (int) $id : null;
    } catch (Throwable $e) {
        return null;
    }
}

/**
 * Find an open maintenance request (pending/in_progress) for a fixed asset.
 *
 * @return int|null Maintenance request id, or null when none is open.
 */
function open_maintenance_request_for_fixed_asset($fixedAssetId) {
    global $pdo;

    $fixedAssetId = (int) $fixedAssetId;
    if ($fixedAssetId <= 0) {
        return null;
    }

    ensure_asset_return_schema();

    try {
        $stmt = $pdo->prepare(
            "SELECT id FROM asset_maintenance
             WHERE asset_id = ? AND status IN ('pending', 'in_progress')
             LIMIT 1"
        );
        $stmt->execute([$fixedAssetId]);
        $id = $stmt->fetchColumn();
        return $id ? (int) $id : null;
    } catch (Throwable $e) {
        return null;
    }
}

/**
 * Create one high-priority maintenance request for a returned asset.
 * Skips the insert when an open request already exists for the same return.
 */
function create_asset_return_maintenance_request(array $asset, $condition, $notes = '', $userId = null) {
    global $pdo;

    $employeeAssetId = (int) ($asset['id'] ?? 0);
    if ($employeeAssetId <= 0) {
        return false;
    }
    ensure_asset_return_schema();

    try {
        $duplicate = $pdo->prepare(
            "SELECT id FROM asset_maintenance
             WHERE source = 'asset_return' AND employee_asset_id = ?
               AND status IN ('pending', 'in_progress')
             LIMIT 1"
        );
        $duplicate->execute([$employeeAssetId]);
        if ($duplicate->fetchColumn()) {
            return false;
        }
    } catch (Throwable $ignored) {
        // If the table/columns are unavailable the insert below will report it.
    }

    $fixedAssetId = !empty($asset['fixed_asset_id']) ? (int) $asset['fixed_asset_id'] : null;
    $condition = strtolower(trim((string) $condition));
    $description = 'Asset returned in ' . $condition . ' condition.'
        . ($notes !== '' ? ' ' . $notes : '');
    $createdBy = $userId !== null ? (int) $userId : null;

    $fullInsert = "INSERT INTO asset_maintenance
        (asset_id, maintenance_date, maintenance_type, description, performed_by, notes, created_by,
         source, employee_asset_id, status, priority, due_date)
        VALUES (?, CURDATE(), 'Repair', ?, 'HR Department', 'Automatically created from asset return', ?,
                'asset_return', ?, 'pending', 'high', DATE_ADD(CURDATE(), INTERVAL 1 DAY))";

    try {
        $pdo->prepare($fullInsert)->execute([$fixedAssetId, $description, $createdBy, $employeeAssetId]);
    } catch (Throwable $firstError) {
        try {
            // Older schemas may still require a non-null asset_id.
            $pdo->prepare($fullInsert)->execute([0, $description, $createdBy, $employeeAssetId]);
        } catch (Throwable $secondError) {
            try {
                $pdo->prepare(
                    "INSERT INTO asset_maintenance
                        (asset_id, maintenance_date, maintenance_type, description, performed_by, notes, created_by)
                     VALUES (?, CURDATE(), 'Repair', ?, 'HR Department', 'Automatically created from asset return', ?)"
                )->execute([$fixedAssetId ?: 0, $description, $createdBy]);
            } catch (Throwable $thirdError) {
                error_log('ASSET_RETURN_MAINTENANCE_ERROR: ' . $thirdError->getMessage());
                return false;
            }
        }
    }

    try {
        $maintenanceUsers = $pdo->query(
            "SELECT DISTINCT u.id
             FROM users u
             LEFT JOIN user_permissions up ON up.user_id = u.id
             WHERE u.role IN ('admin', 'maintenance', 'manager')
                OR (up.module = 'assets' AND up.can_edit = 1)"
        )->fetchAll();
        if (!$maintenanceUsers) {
            $maintenanceUsers = $pdo->query("SELECT id FROM users WHERE role IN ('admin', 'maintenance', 'manager')")->fetchAll();
        }
        $notify = $pdo->prepare("INSERT INTO user_notifications(user_id, message, link) VALUES(?,?,?)");
        $message = mb_substr('Maintenance request created for returned asset: ' . ($asset['asset_name'] ?? 'Asset'), 0, 255);
        foreach ($maintenanceUsers as $maintenanceUser) {
            $notify->execute([(int) $maintenanceUser['id'], $message, '/block_plant/assets/maintenance.php']);
        }
    } catch (Throwable $ignored) {
    }

    return true;
}

/**
 * Mark one employee asset returned/cleared, record its condition and raise
 * maintenance when the condition requires it. Used by both Return Asset and
 * Asset Clearance so the two screens keep the same rules.
 *
 * @return array{asset:array,condition:string,maintenance_created:bool,return_date:string}
 */
function return_employee_asset($employeeAssetId, $conditionReturned, $notes = '', $returnDate = null, $expectedEmployeeId = null, $userId = null) {
    global $pdo;

    $employeeAssetId = (int) $employeeAssetId;
    $conditionReturned = trim((string) $conditionReturned);
    $notes = trim((string) $notes);
    $returnDate = $returnDate ?: date('Y-m-d');
    $userId = $userId !== null ? (int) $userId : (int) ($_SESSION['user_id'] ?? 0);

    if ($employeeAssetId <= 0) {
        throw new InvalidArgumentException('Select an asset to clear.');
    }
    if (!in_array($conditionReturned, asset_return_conditions(), true)) {
        throw new InvalidArgumentException('Select a valid returned condition.');
    }
    if (!is_valid_date_string($returnDate)) {
        throw new InvalidArgumentException('Select a valid return/clearance date.');
    }
    if ($returnDate > date('Y-m-d')) {
        throw new InvalidArgumentException('The return/clearance date cannot be in the future.');
    }
    if (mb_strlen($notes) > 2000) {
        throw new InvalidArgumentException('Notes must be 2,000 characters or fewer.');
    }

    ensure_asset_return_schema();

    $stmt = $pdo->prepare(
        "SELECT id, employee_id, asset_name, asset_type, serial_number, fixed_asset_id, status, notes
         FROM employee_assets WHERE id = ?"
    );
    $stmt->execute([$employeeAssetId]);
    $asset = $stmt->fetch();
    if (!$asset) {
        throw new RuntimeException('The employee asset was not found.');
    }
    if ($expectedEmployeeId !== null && (int) $asset['employee_id'] !== (int) $expectedEmployeeId) {
        throw new RuntimeException('The selected asset does not belong to this employee.');
    }
    if ($asset['status'] !== 'issued') {
        throw new RuntimeException('This asset has already been returned or cleared.');
    }

    $update = $pdo->prepare(
        "UPDATE employee_assets
         SET status = 'returned', return_date = ?, condition_returned = ?, notes = ?
         WHERE id = ? AND status = 'issued'"
    );
    $update->execute([$returnDate, $conditionReturned, $notes !== '' ? $notes : null, $employeeAssetId]);
    if ($update->rowCount() !== 1) {
        throw new RuntimeException('This asset has already been returned or cleared.');
    }

    if (!empty($asset['fixed_asset_id'])) {
        try {
            $pdo->prepare("UPDATE assets SET status = 1, condition_status = ? WHERE id = ?")
                ->execute([asset_return_condition_to_asset_status($conditionReturned), (int) $asset['fixed_asset_id']]);
        } catch (Throwable $ignored) {
        }
    }

    $maintenanceCreated = false;
    if (asset_return_condition_requires_maintenance($conditionReturned)) {
        $maintenanceCreated = create_asset_return_maintenance_request($asset, $conditionReturned, $notes, $userId);
    }

    log_activity(
        'update',
        'hr',
        $employeeAssetId,
        'Asset returned/cleared in ' . $conditionReturned . ' condition: ' . $asset['asset_name']
            . ($maintenanceCreated ? ' (maintenance requested)' : '')
    );

    return [
        'asset' => $asset,
        'condition' => $conditionReturned,
        'maintenance_created' => $maintenanceCreated,
        'return_date' => $returnDate,
    ];
}

/**
 * Post an approved expense to the cashbook exactly once.
 * Returns false when the voucher was already posted.
 */
function post_expense_cashbook($voucherNo, $expenseDate, $description, $amount, $paymentMethod, $userId) {
    global $pdo;
    $check = $pdo->prepare("SELECT COUNT(*) FROM cashbook WHERE transaction_type = 'expense' AND reference_no = ?");
    $check->execute([$voucherNo]);
    if ((int) $check->fetchColumn() > 0) {
        return false;
    }
    $stmt = $pdo->prepare("INSERT INTO cashbook(transaction_date, transaction_type, reference_no, description, amount, payment_method, created_by) VALUES(?,'expense',?,?,?,?,?)");
    $stmt->execute([
        $expenseDate,
        $voucherNo,
        mb_substr((string) $description, 0, 255),
        round((float) $amount, 2),
        $paymentMethod,
        $userId,
    ]);
    return true;
}

