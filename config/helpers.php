/**
 * Notify every active user with one of the given roles.
 * Optionally exclude a user (usually the actor) to avoid self-notification.
 */
function notify_role($roles, $message, $link = null, $excludeUserId = null) {
    global $pdo;
    $roles = is_array($roles) ? $roles : [$roles];
    $roles = array_values(array_filter($roles));
    if (!$roles) {
        return 0;
    }
    $placeholders = implode(',', array_fill(0, count($roles), '?'));
    $sql = "SELECT id FROM users WHERE role IN ({$placeholders}) AND status = 1";
    $params = $roles;
    if ($excludeUserId) {
        $sql .= " AND id != ?";
        $params[] = (int) $excludeUserId;
    }
    $stmt = $pdo->prepare($sql);
    $stmt->execute($params);
    $ids = $stmt->fetchAll(PDO::FETCH_COLUMN);
    $count = 0;
    foreach ($ids as $uid) {
        if (notify_user($uid, $message, $link)) {
            $count++;
        }
    }
    return $count;
}

