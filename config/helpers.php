/**
 * Revocations that overlap a warning period, optionally limited to one
 * department. Overlap is used because the register's end date can move (for
 * example, month-to-date) while the same warning remains revoked.
 *
 * @return array<int,array<string,mixed>>
 */
function attendance_warning_revocations($from, $to, $department = '') {
    global $pdo;
    [$from, $to] = attendance_report_bounds($from, $to);
    ensure_attendance_warning_schema();
    $sql = "SELECT r.*, e.name AS employee_name, e.employee_code, e.department,
                   u.name AS revoked_by_name
            FROM attendance_warning_revocations r
            JOIN employees e ON e.id = r.employee_id
            LEFT JOIN users u ON u.id = r.revoked_by
            WHERE r.period_from <= ? AND r.period_to >= ?";
    $params = [$to, $from];
    $department = trim((string) $department);
    if ($department !== '') {
        $sql .= " AND e.department = ?";
        $params[] = $department;
    }
    $sql .= " ORDER BY r.revoked_at DESC, e.name";
    try {
        $stmt = $pdo->prepare($sql);
        $stmt->execute($params);
        return $stmt->fetchAll();
    } catch (Throwable $e) {
        return [];
    }
}

/**
 * True when every absence date in the warning falls inside the revoked period.
 *
 * The period boundaries can differ from the current register because the
 * register's end date moves with the selected period. The absence dates decide
 * whether this is the same warning.
 *
 * @param array<string,mixed> $revocation
 * @param array<int,string>   $absenceDates
 */
function attendance_warning_revocation_covers($revocation, $absenceDates) {
    if (!$revocation || empty($absenceDates)) {
        return false;
    }
    $from = (string) ($revocation['period_from'] ?? '');
    $to = (string) ($revocation['period_to'] ?? '');
    if ($from === '' || $to === '') {
        return false;
    }
    foreach ($absenceDates as $date) {
        $date = (string) $date;
        if ($date < $from || $date > $to) {
            return false;
        }
    }
    return true;
}

/**
 * The revocation that covers the warning's recorded absence dates.
 *
 * @param array<int,string> $absenceDates
 * @return array<string,mixed>|null
 */
function attendance_warning_effective_revocation($employeeId, $from, $to, $absenceDates = []) {
    global $pdo;
    $employeeId = (int) $employeeId;
    [$from, $to] = attendance_report_bounds($from, $to);
    if ($employeeId <= 0) {
        return null;
    }
    ensure_attendance_warning_schema();
    $absenceDates = array_values(array_filter(array_map('strval', (array) $absenceDates)));
    if (empty($absenceDates)) {
        return attendance_warning_revocation($employeeId, $from, $to);
    }
    $minDate = min($absenceDates);
    $maxDate = max($absenceDates);
    try {
        $stmt = $pdo->prepare(
            "SELECT r.*, u.name AS revoked_by_name
             FROM attendance_warning_revocations r
             LEFT JOIN users u ON u.id = r.revoked_by
             WHERE r.employee_id = ? AND r.period_from <= ? AND r.period_to >= ?
             ORDER BY r.revoked_at DESC"
        );
        $stmt->execute([$employeeId, $maxDate, $minDate]);
        foreach ($stmt->fetchAll() as $row) {
            if (attendance_warning_revocation_covers($row, $absenceDates)) {
                return $row;
            }
        }
        return null;
    } catch (Throwable $e) {
        return null;
    }
}

/**
 * Mark a warning letter as revoked for an employee and exact period.
 *
 * @return int Revocation ID, or 0 on failure.
