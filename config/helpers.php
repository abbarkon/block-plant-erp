    return isset($map[$status]) ? t($map[$status]) : ($status === '' ? '-' : ucfirst($status));
}

/**
 * Add the shift columns used by the daily register when an existing
 * installation has not run the updated database.sql yet.
 */
function ensure_attendance_shift_schema() {
    static $checked = false;
    if ($checked) {
        return;
    }
    $checked = true;
    global $pdo;
    try {
        $employeeColumns = array_column($pdo->query("SHOW COLUMNS FROM employees")->fetchAll(), 'Field');
        if (!in_array('shift', $employeeColumns, true)) {
            $pdo->exec("ALTER TABLE employees ADD COLUMN shift VARCHAR(10) NOT NULL DEFAULT 'morning'");
        }
        $attendanceColumns = array_column($pdo->query("SHOW COLUMNS FROM attendance")->fetchAll(), 'Field');
        if (!in_array('shift', $attendanceColumns, true)) {
            $pdo->exec("ALTER TABLE attendance ADD COLUMN shift VARCHAR(10) NULL");
        }
    } catch (Throwable $e) {
        // Older or locked-down databases keep working with the default shift.
    }
}

/**
 * Company working sessions for a date, in standard 24-hour clock time.
 *
 * The company works two sessions, described here in Ethiopian local time:
 *   morning   2:30 – 6:30  (08:30 – 12:30), Friday 2:30 – 5:30 (08:30 – 11:30)
 *   afternoon 7:30 – 11:30 (13:30 – 17:30)
 * An employee is late when clocking in after 2:45 (08:45) or 7:45 (13:45).
 *
 * @return array<string,array{start:string,end:string,grace:string}>
 */
function attendance_work_sessions($date = null) {
    $date = $date ?: date('Y-m-d');
    $isFriday = is_valid_date_string($date) && (int) date('N', strtotime($date)) === 5;
    return [
        'morning' => [
            'start' => '08:30',
            'end' => $isFriday ? '11:30' : '12:30',
            'grace' => '08:45',
        ],
        'afternoon' => [
            'start' => '13:30',
            'end' => '17:30',
            'grace' => '13:45',
        ],
    ];
}

/**
 * @return array<string,array{en:string,am:string}>
 */
function attendance_shift_options() {
    return [
        'morning' => ['en' => 'Morning', 'am' => 'ጠዋት'],
        'afternoon' => ['en' => 'Afternoon', 'am' => 'ከሰዓት'],
    ];
}

/**
 * Localized shift name, or an empty string for an unknown shift.
 */
function attendance_shift_label($shift) {
    $shift = strtolower(trim((string) $shift));
    $options = attendance_shift_options();
    if (!isset($options[$shift])) {
        return '';
    }
    return app_lang() === 'am' ? $options[$shift]['am'] : $options[$shift]['en'];
}

/**
 * Ethiopian local-clock label for a standard 24-hour time.
 * '08:30' -> '2:30 AM', '13:30' -> '7:30 PM'.
 */
function attendance_local_time_label($time) {
    $time = substr(trim((string) $time), 0, 5);
    if (!preg_match('/^([01]\d|2[0-3]):([0-5]\d)$/', $time, $matches)) {
        return '';
    }
    $hour = (int) $matches[1];
    $local = ($hour + 6) % 12;
    if ($local === 0) {
        $local = 12;
    }
    return $local . ':' . $matches[2] . ' ' . ($hour < 12 ? 'AM' : 'PM');
}

/**
 * Minutes late for a clock-in against the shift's grace time.
 * Returns 0 when the employee is on time or no time was recorded.
 */
function attendance_late_minutes($clockIn, $shift, $date = null) {
    $sessions = attendance_work_sessions($date);
    $shift = strtolower(trim((string) $shift));
    if (!isset($sessions[$shift])) {
        $shift = 'morning';
    }
    $clockIn = substr(trim((string) $clockIn), 0, 5);
    if (!preg_match('/^([01]\d|2[0-3]):([0-5]\d)$/', $clockIn)) {
        return 0;
    }
    $grace = $sessions[$shift]['grace'];
    if ($clockIn <= $grace) {
        return 0;
    }
    $diff = strtotime('2000-01-01 ' . $clockIn) - strtotime('2000-01-01 ' . $grace);
    return max(0, (int) round($diff / 60));
}

/**
 * Apply the company late rule to a recorded clock-in.
 *
 * Only working statuses are affected: present/late follow the clock-in time,
 * while absent, leave and half-day are left untouched.
 */
function attendance_status_with_clock($status, $clockIn, $shift, $date = null) {
    $status = strtolower(trim((string) $status));
    if (!in_array($status, ['present', 'late'], true)) {
        return $status;
    }
    if (trim((string) $clockIn) === '') {
        return $status;
    }
    return attendance_late_minutes($clockIn, $shift, $date) > 0 ? 'late' : 'present';
}

