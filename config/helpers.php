/**
 * Recorded full-day absences on working days for one employee.
 *
 * @return array<int,array{date:string,notes:string}>
 */
function attendance_absence_days($employeeId, $from, $to) {
    global $pdo;
    $employeeId = (int) $employeeId;
    [$from, $to] = attendance_report_bounds($from, $to);
    $today = date('Y-m-d');
    if ($to > $today) {
        $to = $today;
    }
    if ($employeeId <= 0 || $from > $to) {
        return [];
    }

    try {
        $stmt = $pdo->prepare(
            "SELECT a.attendance_date, a.notes
             FROM attendance a
             JOIN employees e ON e.id = a.employee_id
             WHERE a.employee_id = ? AND a.status = 'absent' AND a.attendance_date BETWEEN ? AND ?
               AND (e.date_of_joining IS NULL OR a.attendance_date >= e.date_of_joining)
             ORDER BY a.attendance_date"
        );
        $stmt->execute([$employeeId, $from, $to]);
        $days = [];
        foreach ($stmt->fetchAll() as $row) {
            $date = (string) $row['attendance_date'];
            if (is_working_day($date)) {
                $days[] = [
                    'date' => $date,
                    'notes' => (string) ($row['notes'] ?? ''),
                ];
            }
        }
        return $days;
    } catch (Throwable $e) {
        return [];
    }
}

/**
 * Number of working days strictly between two dates. Used to treat Friday and
 * Monday as consecutive working days while skipping the weekend.
 */
function working_days_between($startDate, $endDate, ?array $workingDays = null) {
    if (!is_valid_date_string($startDate) || !is_valid_date_string($endDate) || $endDate <= $startDate) {
        return 0;
    }
    $start = strtotime($startDate);
    $end = strtotime($endDate);
    if ($start === false || $end === false) {
        return 0;
    }

    $count = 0;
    for ($cursor = strtotime('+1 day', $start); $cursor !== false && $cursor < $end; $cursor = strtotime('+1 day', $cursor)) {
        if (is_working_day(date('Y-m-d', $cursor), $workingDays)) {
            $count++;
        }
    }
    return $count;
}

/**
 * Summarise absent dates and the longest consecutive working-day run.
 *
 * @return array{total:int,longest_consecutive:int,dates:array<int,string>,first_date:?string,last_date:?string}
 */
function attendance_absence_summary(array $days) {
    $dateMap = [];
    foreach ($days as $day) {
        $date = is_array($day) ? (string) ($day['date'] ?? '') : (string) $day;
        if (is_valid_date_string($date)) {
            $dateMap[$date] = true;
        }
    }
    $dates = array_keys($dateMap);
    sort($dates);

    $longest = 0;
    $current = 0;
    $previous = null;
    foreach ($dates as $date) {
        if ($previous === null || working_days_between($previous, $date) === 0) {
            $current++;
        } else {
            $current = 1;
        }
        $longest = max($longest, $current);
        $previous = $date;
    }

    return [
        'total' => count($dates),
        'longest_consecutive' => $longest,
        'dates' => $dates,
        'first_date' => $dates[0] ?? null,
        'last_date' => $dates ? $dates[count($dates) - 1] : null,
    ];
}

/**
 * Active employees with at least $minimumDays recorded full-day absences on
 * working days in the range. Approved leave and half-days are not counted.
 *
 * @return array<int,array>
 */
function attendance_warning_candidates($from, $to, $department = '', $minimumDays = 3) {
    global $pdo;
    [$from, $to] = attendance_report_bounds($from, $to);
    $today = date('Y-m-d');
    if ($to > $today) {
        $to = $today;
    }
    $minimumDays = max(1, (int) $minimumDays);
    if ($from > $to) {
        return [];
    }

    $sql = "SELECT e.id, e.name, e.employee_code, e.department, e.designation,
                   a.attendance_date, a.notes
            FROM employees e
            JOIN attendance a ON a.employee_id = e.id
            WHERE e.status = 1
              AND a.status = 'absent'
              AND a.attendance_date BETWEEN ? AND ?
              AND (e.date_of_joining IS NULL OR a.attendance_date >= e.date_of_joining)";
    $params = [$from, $to];

    $department = trim((string) $department);
    if ($department !== '') {
        $sql .= " AND e.department = ?";
        $params[] = $department;
    }
    $sql .= " ORDER BY e.name, a.attendance_date";

    try {
        $stmt = $pdo->prepare($sql);
        $stmt->execute($params);
    } catch (Throwable $e) {
        return [];
    }

    $employees = [];
    foreach ($stmt->fetchAll() as $row) {
        $date = (string) $row['attendance_date'];
        if (!is_working_day($date)) {
            continue;
        }
        $id = (int) $row['id'];
        if (!isset($employees[$id])) {
            $employees[$id] = [
                'id' => $id,
                'name' => (string) $row['name'],
                'employee_code' => (string) $row['employee_code'],
                'department' => (string) ($row['department'] ?? ''),
                'designation' => (string) ($row['designation'] ?? ''),
                'days' => [],
            ];
        }
        $employees[$id]['days'][] = [
            'date' => $date,
            'notes' => (string) ($row['notes'] ?? ''),
        ];
    }

    $candidates = [];
    foreach ($employees as $employee) {
        $summary = attendance_absence_summary($employee['days']);
        if ($summary['total'] >= $minimumDays) {
            $employee['summary'] = $summary;
            $candidates[] = $employee;
        }
    }
    usort($candidates, function ($a, $b) {
        if ($a['summary']['total'] !== $b['summary']['total']) {
            return $b['summary']['total'] <=> $a['summary']['total'];
        }
        return strcasecmp($a['name'], $b['name']);
    });
    return $candidates;
}

/**
 * Annual leave balances: one row per employee/year holds the entitlement and
 * any manual adjustment. Carry-forward is derived automatically from the
 * previous year's unused balance, so unused days roll into the next year.
 */
function ensure_leave_balances_schema() {
    global $pdo;
    static $ensured = false;
    if ($ensured) {
        return;
    }
    try {
        $pdo->exec("CREATE TABLE IF NOT EXISTS leave_balances (
            id INT AUTO_INCREMENT PRIMARY KEY,
            employee_id INT NOT NULL,
            year INT NOT NULL,
            leave_type VARCHAR(50) NOT NULL DEFAULT 'Annual Leave',
            entitlement_days DECIMAL(6,1) NOT NULL DEFAULT 0,
            adjustment_days DECIMAL(6,1) NOT NULL DEFAULT 0,
            notes VARCHAR(255) NULL,
            updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
            UNIQUE KEY unique_leave_balance (employee_id, year, leave_type),
            FOREIGN KEY (employee_id) REFERENCES employees(id)
        )");
    } catch (Throwable $e) {
        // Table already exists or cannot be created here; callers degrade to 0.
    }
    $ensured = true;
}

/**
 * Approved annual-leave days per calendar year (date ranges are split across
 * year boundaries and clipped to the requested window).
 *
 * @return array<int,float> year => days
 */
function annual_leave_used_by_year($employeeId, $startYear, $endYear) {
    global $pdo;
    $employeeId = (int) $employeeId;
    $startYear = (int) $startYear;
    $endYear = (int) $endYear;
    $map = [];
    if ($employeeId <= 0 || $endYear < $startYear) {
        return $map;
    }

    $start = sprintf('%04d-01-01', $startYear);
    $end = sprintf('%04d-12-31', $endYear);
    try {
        $stmt = $pdo->prepare(
            "SELECT from_date, to_date FROM leave_requests
             WHERE employee_id = ? AND status = 'approved'
               AND LOWER(leave_type) LIKE '%annual%'
               AND from_date <= ? AND to_date >= ?"
        );
        $stmt->execute([$employeeId, $end, $start]);
        foreach ($stmt->fetchAll() as $leave) {
            $cursor = max(strtotime($leave['from_date']), strtotime($start));
            $last = min(strtotime($leave['to_date']), strtotime($end));
            while ($cursor !== false && $cursor <= $last) {
                $y = (int) date('Y', $cursor);
                $map[$y] = ($map[$y] ?? 0) + 1;
                $cursor = strtotime('+1 day', $cursor);
            }
        }
    } catch (Throwable $e) {
        return [];
    }
    return $map;
}

/**
 * Annual leave position for an employee in a year.
 *
 * Entitlement and adjustment come from leave_balances. Carried-forward days are
 * the positive unused balance of the previous year, chained back to the
 * employee's joining year (or earliest stored balance).
 *
 * @return array{year:int,entitlement_days:float,carried_forward_days:float,adjustment_days:float,used_days:float,available_days:float}
 */
function annual_leave_balance($employeeId, $year) {
    global $pdo;
    ensure_leave_balances_schema();
    $employeeId = (int) $employeeId;
    $year = (int) $year;

    $result = [
        'year' => $year,
        'entitlement_days' => 0.0,
        'carried_forward_days' => 0.0,
        'adjustment_days' => 0.0,
        'used_days' => 0.0,
        'available_days' => 0.0,
    ];
    if ($employeeId <= 0 || $year < 1900) {
        return $result;
    }

    $startYear = $year;
    try {
        $stmt = $pdo->prepare("SELECT date_of_joining FROM employees WHERE id = ?");
        $stmt->execute([$employeeId]);
        $joined = $stmt->fetchColumn();
        if (!empty($joined)) {
            $startYear = (int) date('Y', strtotime($joined));
        }
    } catch (Throwable $e) {
        $startYear = $year;
    }

    $rows = [];
    try {
        $stmt = $pdo->prepare(
            "SELECT year, entitlement_days, adjustment_days FROM leave_balances
             WHERE employee_id = ? AND leave_type = 'Annual Leave' AND year <= ?
             ORDER BY year"
        );
        $stmt->execute([$employeeId, $year]);
        foreach ($stmt->fetchAll() as $row) {
            $rows[(int) $row['year']] = $row;
        }
    } catch (Throwable $e) {
        $rows = [];
    }
    if ($rows) {
        $earliest = min(array_keys($rows));
        if ($earliest < $startYear) {
            $startYear = $earliest;
        }
    }
    if ($startYear > $year) {
        $startYear = $year;
    }
    if ($year - $startYear > 25) {
        $startYear = $year - 25;
    }

    $usedByYear = annual_leave_used_by_year($employeeId, $startYear, $year);
    $carry = 0.0;
    for ($y = $startYear; $y <= $year; $y++) {
        $row = $rows[$y] ?? null;
        $entitlement = $row ? (float) $row['entitlement_days'] : 0.0;
        $adjustment = $row ? (float) $row['adjustment_days'] : 0.0;
        $used = (float) ($usedByYear[$y] ?? 0);
        $available = $entitlement + $carry + $adjustment - $used;

        if ($y === $year) {
            $result['entitlement_days'] = round($entitlement, 1);
            $result['carried_forward_days'] = round($carry, 1);
            $result['adjustment_days'] = round($adjustment, 1);
            $result['used_days'] = round($used, 1);
            $result['available_days'] = round($available, 1);
            return $result;
        }
        // Unused days roll into the next year; negative balances do not carry.
        $carry = max(0.0, $available);
    }

    return $result;
}

/**
 * Split a leave request into the number of days that fall inside each
 * calendar year. Annual leave can cross a year boundary, and each year has
 * its own balance.
 *
 * @return array<int,int> year => days
 */
function leave_request_days_by_year($fromDate, $toDate) {
    $map = [];
    if (!is_valid_date_string($fromDate) || !is_valid_date_string($toDate) || $toDate < $fromDate) {
        return $map;
    }

    $startYear = (int) date('Y', strtotime($fromDate));
    $endYear = (int) date('Y', strtotime($toDate));
    for ($year = $startYear; $year <= $endYear; $year++) {
        $rangeStart = max(strtotime($fromDate), strtotime($year . '-01-01'));
        $rangeEnd = min(strtotime($toDate), strtotime($year . '-12-31'));
        if ($rangeStart !== false && $rangeEnd !== false && $rangeStart <= $rangeEnd) {
            $map[$year] = (int) (($rangeEnd - $rangeStart) / 86400) + 1;
        }
    }
    return $map;
}

/**
 * Pending annual-leave days per calendar year. Used when validating a new
 * request or approving an existing one so several pending requests cannot
 * collectively overbook the same entitlement.
 *
 * @return array<int,float> year => days
 */
function annual_leave_pending_by_year($employeeId, $startYear, $endYear, $excludeRequestId = 0) {
    global $pdo;
    $map = [];
    $employeeId = (int) $employeeId;
    $startYear = (int) $startYear;
    $endYear = (int) $endYear;
    $excludeRequestId = (int) $excludeRequestId;
    if ($employeeId <= 0 || $endYear < $startYear) {
        return $map;
    }

    $start = sprintf('%04d-01-01', $startYear);
    $end = sprintf('%04d-12-31', $endYear);
    try {
        $sql = "SELECT from_date, to_date FROM leave_requests
                WHERE employee_id = ? AND status = 'pending'
                  AND LOWER(leave_type) LIKE '%annual%'
                  AND from_date <= ? AND to_date >= ?";
        $params = [$employeeId, $end, $start];
        if ($excludeRequestId > 0) {
            $sql .= " AND id <> ?";
            $params[] = $excludeRequestId;
        }
        $stmt = $pdo->prepare($sql);
        $stmt->execute($params);
        foreach ($stmt->fetchAll() as $leave) {
            foreach (leave_request_days_by_year($leave['from_date'], $leave['to_date']) as $year => $days) {
                if ($year >= $startYear && $year <= $endYear) {
                    $map[$year] = ($map[$year] ?? 0) + $days;
                }
            }
        }
    } catch (Throwable $e) {
        return [];
    }
    return $map;
}

/**
 * Return the first year in which an annual-leave request would exceed the
 * available balance, or null when the request fits. Approved days come from
 * annual_leave_balance(); other pending annual requests are reserved too.
 *
 * @return array{year:int,requested:float,available:float,shortfall:float}|null
 */
function annual_leave_request_excess($employeeId, $fromDate, $toDate, $excludeRequestId = 0) {
    $requestedByYear = leave_request_days_by_year($fromDate, $toDate);
    if (!$requestedByYear) {
        return null;
    }

    $startYear = min(array_keys($requestedByYear));
    $endYear = max(array_keys($requestedByYear));
    $pendingByYear = annual_leave_pending_by_year($employeeId, $startYear, $endYear, $excludeRequestId);
    $pendingCarryReduction = 0.0;

    for ($year = $startYear; $year <= $endYear; $year++) {
        if (!isset($requestedByYear[$year])) {
            continue;
        }
        $balance = annual_leave_balance($employeeId, $year);
        $pending = (float) ($pendingByYear[$year] ?? 0);
        $available = (float) $balance['available_days'] - $pending - $pendingCarryReduction;
        $requested = (float) $requestedByYear[$year];

        if ($requested > $available + 0.0001) {
            return [
                'year' => $year,
                'requested' => round($requested, 1),
                'available' => round($available, 1),
                'shortfall' => round($requested - $available, 1),
            ];
        }

        // Pending days in this year also reduce the balance that can roll into
        // the following year, so carry that reduction forward.
        if ($pending > 0) {
            $pendingCarryReduction += min($pending, max(0.0, (float) $balance['available_days'] - $pendingCarryReduction));
        }
    }

    return null;
}

